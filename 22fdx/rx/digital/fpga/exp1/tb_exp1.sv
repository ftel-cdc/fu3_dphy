// TN1 testbench (fpga/PLAN_TN1_TN3.md §1, fpga/PLAN_TN1_FAIR.md). One D-PHY line, from dphy_line_gen, drives
// two receivers:
// - AMD's D-PHY RX: mipi_dphy 4.3, SLAVE, generated by exp1.tcl as module xrx for the rate and lane count
//   of the build;
// - ftel_dphy_rx: the ASIC RTL of logical/, unchanged, behind IBUFDS_DPHY, the D-PHY
//   input buffer of AMD's receiver (default), or behind afe_model (+AFE=model).
// Each PPI is written as an ILA-style CSV (ppi_csv_mon). fpga/tools/csi2_dump.py bursts then compares
// both with the truth file of the line generator.
// Parameter NL = lanes (1, 2 or 4), set at elaboration. Plusargs, all optional:
//   +OUTDIR=<dir>                 truth.txt, xil_ppi.csv, ftel_ppi.csv (default .)
//   +RATE=<Mb/s>                  line rate, the one xrx was built for (default 1440)
//   +LENS=<n,n,...>               payload bytes per lane of each burst (default 1,2,3,4,5,8,16,64,256,1024)
//   +REPEAT=<n>                   times the list of lengths is sent (default 1)
//   +PATTERN=counter|prbs9|synclike
//   +UNEVEN=1                     lanes NL/2..NL-1 carry one byte less, as in a CSI-2 packet whose length
//                                 is not a multiple of NL
//   +TLPX= +THS_PREPARE= +THS_ZERO= +THS_TRAIL= +THS_EXIT= +TCLK_PREPARE= +TCLK_ZERO=   in ns
//   +PREP=min|max  +ZERO=min  +TRAIL=min|max  +EXIT=min  +LPX=min    D-PHY v1.1 limits at the rate
//                                 (TRAIL=max: TEOT,max - 8 UI = 105 ns + 4 UI, room for the jitter)
//   +SKEW0..3=<ps> +CLK_SKEW=<ps>  extra delay of a data lane / of the clock lane at the pads
//   +TRAIL_JITTER=1               0..7 random extra trail bits per lane and burst (LP-11 at every phase
//                                 of the byte clock)
//   +EOT_JUNK=<ns>                the last <ns> of the trail are random bits (transition junk; 40 = the
//                                 THS-SKIP,min that the HAS assumes)
//   +SEED=<n>                     seed of the random trail and junk bits (default: the simulator's)
//   +HS_SETTLE= +CLK_SETTLE= +EOT_SKIP= +TINIT=   run-time fields of ftel_dphy_rx (default: reset values)
//   +FTEL=0                       hold ftel_dphy_rx in reset: AMD's receiver alone
//   +AFE=xil|model                front end of ftel_dphy_rx: IBUFDS_DPHY as in AMD's receiver (default), or
//                                 afe_model (LP-00 during HS, as on silicon; HS-RX output 0 outside HS)
//   +AFE_NOISE=1                  random HS-RX output during LP-00 (afe_model, needs +AFE=model)
//   +TIMEOUT_US=<us>              simulation limit (default 600)
//   +CORE_HALF=<ns>               half period of core_clk (default 2.5); 2.501 (400 ppm slow) lets core_clk
//                                 drift against the line, so LP-11 meets it at every phase
// Defaults of the line timing sit inside the D-PHY v1.1 ranges at the rate (see p_main).
// Compile with TN1_STUB defined for the build with xrx_stub.sv, which has no front end to compare.
