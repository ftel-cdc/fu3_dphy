  // The PPI inside xtxss, from its controller to its D-PHY: ports of the D-PHY instance of the subsystem.
  `define TN2B_TP(n, s) u_xtxss.inst.mipi_dphy_0.dl``n``_``s
  logic [3:0][7:0] tp_data;
  logic [3:0]      tp_req, tp_ready;
  assign tp_data  = {`TN2B_TP(3, txdatahs), `TN2B_TP(2, txdatahs), `TN2B_TP(1, txdatahs), `TN2B_TP(0, txdatahs)};
  assign tp_req   = {`TN2B_TP(3, txrequesths), `TN2B_TP(2, txrequesths), `TN2B_TP(1, txrequesths), `TN2B_TP(0, txrequesths)};
  assign tp_ready = {`TN2B_TP(3, txreadyhs), `TN2B_TP(2, txreadyhs), `TN2B_TP(1, txreadyhs), `TN2B_TP(0, txreadyhs)};
  `undef TN2B_TP
  wire t_init_done = u_xtxss.inst.mipi_dphy_0.init_done;
  wire t_cl_req    = u_xtxss.inst.mipi_dphy_0.cl_txrequesths;   // the controller asks its D-PHY for the HS clock

  // ------------------------------------------------------------------ pads
  // The TX drives two copies of the pads, both through continuous assignments, so both carry strong strength
  // (AMD's OBUFDS_DPHY drives strong in LP and supply in HS). xp_* go to xrxss, which passes them on to its
  // buffers through its own continuous assignments. clk_p/clk_n/d_p/d_n, the names of tb_exp1.sv, go to the
  // buffers of ftel_dphy_rx and to afe_model.
  wire           xp_clk_p = t_clk_p;
  wire           xp_clk_n = t_clk_n;
  wire [NL-1:0]  xp_d_p   = t_d_p;
  wire [NL-1:0]  xp_d_n   = t_d_n;
  wire           clk_p    = t_clk_p;
  wire           clk_n    = t_clk_n;
  // +NEG_FRONT=1, the negative test of the front-end check: during HS (as afe_model sees it) the copy of
  // ftel_dphy_rx carries pull strength, so its buffers give LP-00 while AMD's still follow the HS levels.
  bit            neg_front = 1'b0;
  wire  [NL-1:0] d_p, d_n;
  logic [NL-1:0] a_in_hs;
  for (genvar l = 0; l < NL; l++) begin : g_pad
    assign (strong1, strong0) d_p[l] = (neg_front && a_in_hs[l]) ? 1'bz : xp_d_p[l];
    assign (pull1, pull0)     d_p[l] = (neg_front && a_in_hs[l]) ? xp_d_p[l] : 1'bz;
    assign (strong1, strong0) d_n[l] = (neg_front && a_in_hs[l]) ? 1'bz : xp_d_n[l];
    assign (pull1, pull0)     d_n[l] = (neg_front && a_in_hs[l]) ? xp_d_n[l] : 1'bz;
  end

  // ------------------------------------------------------------------ R-X: AMD's CSI-2 receiver with its D-PHY
  logic [7:0]          x_araddr, x_awaddr;
  logic [31:0]         x_rdata, x_wdata;
  logic [3:0]          x_wstrb;
  logic [1:0]          x_bresp, x_rresp;
  logic                x_arready, x_arvalid, x_awready, x_awvalid, x_bready, x_bvalid, x_rready, x_rvalid, x_wready,
                       x_wvalid;
  logic                x_byteclk, x_cl_stop, x_irq;
  logic [NL-1:0][7:0]  x_data;
  logic [NL-1:0]       x_valid, x_active, x_sync, x_errsot, x_errsotsync, x_stop;
  logic [39:0]         x_tdata;
  logic [9:0]          x_tdest;
  logic [95:0]         x_tuser;
  logic                x_tlast, x_tvalid;

  `define TN2B_XM(n) \
      .dl``n``_stopstate (x_stop[n]), .dl``n``_enable (), .dl``n``_rxactivehs (x_active[n]), \
      .dl``n``_rxdatahs (x_data[n]), .dl``n``_rxsynchs (x_sync[n]), .dl``n``_rxvalidhs (x_valid[n]), \
      .dl``n``_rxulpsesc (), .dl``n``_errsoths (x_errsot[n]), .dl``n``_errsotsynchs (x_errsotsync[n]), \
      .dl``n``_erresc (), .dl``n``_errcontrol (),
  xrxss u_xrxss (
    .lite_aclk (lite_clk), .lite_aresetn (rx_aresetn), .dphy_clk_200M (core_clk), .rxbyteclkhs (x_byteclk),
    .clkoutphy_out (), .pll_lock_out (), .system_rst_out (),
    .cl_enable (), .cl_stopstate (x_cl_stop), .cl_rxulpsclknot (),
    `TN2B_XM(0) `TN2B_XM(1) `TN2B_XM(2) `TN2B_XM(3)
    .csirxss_csi_irq (x_irq), .video_aclk (vid_clk), .video_aresetn (rx_aresetn),
    .video_out_tdata (x_tdata), .video_out_tdest (x_tdest), .video_out_tlast (x_tlast), .video_out_tready (1'b1),
    .video_out_tuser (x_tuser), .video_out_tvalid (x_tvalid),
    .mipi_phy_if_clk_n (xp_clk_n), .mipi_phy_if_clk_p (xp_clk_p), .mipi_phy_if_data_n (xp_d_n),
    .mipi_phy_if_data_p (xp_d_p),
    .csirxss_s_axi_araddr (x_araddr), .csirxss_s_axi_arready (x_arready), .csirxss_s_axi_arvalid (x_arvalid),
    .csirxss_s_axi_awaddr (x_awaddr), .csirxss_s_axi_awready (x_awready), .csirxss_s_axi_awvalid (x_awvalid),
    .csirxss_s_axi_bready (x_bready), .csirxss_s_axi_bresp (x_bresp), .csirxss_s_axi_bvalid (x_bvalid),
    .csirxss_s_axi_rdata (x_rdata), .csirxss_s_axi_rready (x_rready), .csirxss_s_axi_rresp (x_rresp),
    .csirxss_s_axi_rvalid (x_rvalid), .csirxss_s_axi_wdata (x_wdata), .csirxss_s_axi_wready (x_wready),
    .csirxss_s_axi_wstrb (x_wstrb), .csirxss_s_axi_wvalid (x_wvalid)
  );
  `undef TN2B_XM

  axil_bfm #(.NAME("R-X"), .AW(8)) u_bus_x (
    .aclk (lite_clk), .aresetn (rx_aresetn), .awaddr (x_awaddr), .awvalid (x_awvalid), .awready (x_awready),
    .wdata (x_wdata), .wstrb (x_wstrb), .wvalid (x_wvalid), .wready (x_wready), .bresp (x_bresp), .bvalid (x_bvalid),
    .bready (x_bready), .araddr (x_araddr), .arvalid (x_arvalid), .arready (x_arready), .rdata (x_rdata),
    .rresp (x_rresp), .rvalid (x_rvalid), .rready (x_rready)
  );

  // ------------------------------------------------------------------ ftel_dphy_rx behind its front end
  logic [NL-1:0]           a_lp_dp, a_lp_dn, a_hs_bit, f_hs_en, f_term_en;
  logic                    a_cl_lp_dp, a_cl_lp_dn, a_cl_hs_clk, a_cl_in_hs, f_cl_hs_en, f_cl_term_en;
  logic                    f_byteclk, f_init_done, f_cl_stop, f_cl_active;
  logic [NL-1:0][7:0]      f_data;
  logic [NL-1:0]           f_valid, f_active, f_sync, f_errsot, f_errsotsync, f_stop;
  logic [NL-1:0][SELW-1:0] f_lane_map;
  logic [C_HS_SETTLE_CYC_W-1:0]     cfg_hs_settle  = C_HS_SETTLE_CYC_RST;
  logic [C_CLK_SETTLE_CYC_W-1:0]    cfg_clk_settle = C_CLK_SETTLE_CYC_RST;
  logic [C_TINIT_CYC_W-1:0]         cfg_tinit      = C_TINIT_CYC_RST;
  logic [C_EOT_SKIP_BYTES_W-1:0]    cfg_eot_skip   = C_EOT_SKIP_BYTES_RST;
  // the PPI towards xrxss_np that TN1 left open or tied (plan §4.3)
  logic                    np_cl_enable, f_cl_ulpsclknot;
  logic [NL-1:0]           np_dl_enable, f_rxulpsesc, f_erresc, f_errcontrol;

  initial for (int l = 0; l < NL; l++) f_lane_map[l] = SELW'(l);

  afe_model #(.NL(NL)) u_afe (
    .clk_p      (clk_p),
    .clk_n      (clk_n),
    .d_p        (d_p),
    .d_n        (d_n),
    .hs_en      (f_hs_en),
    .term_en    (f_term_en),
    .cl_hs_en   (f_cl_hs_en),
    .cl_term_en (f_cl_term_en),
    .lp_dp      (a_lp_dp),
    .lp_dn      (a_lp_dn),
    .hs_bit     (a_hs_bit),
    .cl_lp_dp   (a_cl_lp_dp),
    .cl_lp_dn   (a_cl_lp_dn),
    .cl_hs_clk  (a_cl_hs_clk),
    .in_hs      (a_in_hs),
    .cl_in_hs   (a_cl_in_hs)
  );

  // +AFE=xil (default): IBUFDS_DPHY, the D-PHY input buffer of AMD's receiver, one per lane, with the SIM_DEVICE
  // of AMD's IP; the LP receivers stay enabled, as in AMD's IP. +AFE=model: afe_model. afe_model checks the line
  // state and the enables in both cases. (This block is the code of tb_exp1.sv.)
  logic [NL-1:0] b_lp_dp, b_lp_dn, b_hs_bit, r_lp_dp, r_lp_dn, r_hs_bit;
  logic          b_cl_lp_dp, b_cl_lp_dn, b_cl_hs_clk, r_cl_lp_dp, r_cl_lp_dn, r_cl_hs_clk;
  bit            afe_xil = 1'b1;

  for (genvar l = 0; l < NL; l++) begin : g_ibuf
    IBUFDS_DPHY #(.SIM_DEVICE("VERSAL_PREMIUM")) u_ibuf (
      .HSRX_O       (b_hs_bit[l]),
      .LPRX_O_N     (b_lp_dn[l]),
      .LPRX_O_P     (b_lp_dp[l]),
      .HSRX_DISABLE (~f_hs_en[l]),
      .I            (d_p[l]),
      .IB           (d_n[l]),
      .LPRX_DISABLE (1'b0)
    );
  end

  IBUFDS_DPHY #(.SIM_DEVICE("VERSAL_PREMIUM")) u_cl_ibuf (
    .HSRX_O       (b_cl_hs_clk),
    .LPRX_O_N     (b_cl_lp_dn),
    .LPRX_O_P     (b_cl_lp_dp),
    .HSRX_DISABLE (~f_cl_hs_en),
    .I            (clk_p),
    .IB           (clk_n),
    .LPRX_DISABLE (1'b0)
  );

  assign r_lp_dp     = afe_xil ? b_lp_dp     : a_lp_dp;
  assign r_lp_dn     = afe_xil ? b_lp_dn     : a_lp_dn;
  assign r_hs_bit    = afe_xil ? b_hs_bit    : a_hs_bit;
  assign r_cl_lp_dp  = afe_xil ? b_cl_lp_dp  : a_cl_lp_dp;
  assign r_cl_lp_dn  = afe_xil ? b_cl_lp_dn  : a_cl_lp_dn;
  assign r_cl_hs_clk = afe_xil ? b_cl_hs_clk : a_cl_hs_clk;

  // Same front end, checked: the LP outputs of AMD's buffers (wires of the support module of the D-PHY inside
  // xrxss) must equal those of the buffers above at every change, 2 ps after it (both have a 1 ps delay). The code
  // of tb_exp1.sv; only the path in TN1_XS differs.
  int fe_diffs = 0, fe_events = 0;
`ifndef TN1_STUB
  `define TN1_XS u_xrxss.inst.phy.inst.inst.`XRXSS_SUPPORT
  wire [3:0] x_lp_dp = {`TN1_XS.rx_dl3_lp_dp_w, `TN1_XS.rx_dl2_lp_dp_w, `TN1_XS.rx_dl1_lp_dp_w, `TN1_XS.rx_dl0_lp_dp_w};
  wire [3:0] x_lp_dn = {`TN1_XS.rx_dl3_lp_dn_w, `TN1_XS.rx_dl2_lp_dn_w, `TN1_XS.rx_dl1_lp_dn_w, `TN1_XS.rx_dl0_lp_dn_w};
  wire       x_cl_lp_dp = `TN1_XS.rx_cl_lp_dp_w;
  wire       x_cl_lp_dn = `TN1_XS.rx_cl_lp_dn_w;
  `undef TN1_XS

  always @(x_lp_dp, x_lp_dn, x_cl_lp_dp, x_cl_lp_dn, b_lp_dp, b_lp_dn, b_cl_lp_dp, b_cl_lp_dn) begin : p_fe_chk
    #0.002;
    fe_events++;
    if ({x_cl_lp_dp, x_cl_lp_dn, x_lp_dp[NL-1:0], x_lp_dn[NL-1:0]} !== {b_cl_lp_dp, b_cl_lp_dn, b_lp_dp, b_lp_dn})
      fe_diffs++;
  end
`endif

  // As in tb_exp2a.sv: the pads can leave X at 1 ps and both buffers follow at 2 ps; the comparisons up to 2.5 ps
  // are printed and not counted.
  initial begin : p_fe_start
    #0.0025;
    $display("TB FRONT END CHECK START: comparisons %0d, differences %0d up to 2.5 ps, not counted (the pads can leave X at 1 ps)",
             fe_events, fe_diffs);
    fe_diffs = 0;
    fe_events = 0;
  end

  m_ftel_dphy_rx_wrap #(.PARA_NUM_LANES(NL)) u_ftel (
    .i_dphy_rx_core_clk              (core_clk),
    .i_dphy_rx_phy_core_rst_n        (f_rst_n),
    .i_dphy_rx_cl_enable             (np_cl_enable),
    .i_dphy_rx_dl_enable             (np_dl_enable),
    .i_dphy_rx_forcerxmode           ({NL{1'b0}}),
    .o_dphy_rx_init_done             (f_init_done),
    .o_dphy_rx_cl_stopstate          (f_cl_stop),
    .o_dphy_rx_stopstate             (f_stop),
    .o_dphy_rx_cl_ulpsactivenot      (),
    .o_dphy_rx_ulpsactivenot         (),
    .o_dphy_rx_rxbyteclkhs           (f_byteclk),
    .o_dphy_rx_cl_rxclkactivehs      (f_cl_active),
    .o_dphy_rx_cl_ulpsclknot         (f_cl_ulpsclknot),
    .o_dphy_rx_rxdatahs              (f_data),
    .o_dphy_rx_rxvalidhs             (f_valid),
    .o_dphy_rx_rxactivehs            (f_active),
    .o_dphy_rx_rxsynchs              (f_sync),
    .o_dphy_rx_rxskewcalhs           (),
    .o_dphy_rx_rxclkesc              (),
    .o_dphy_rx_rxlpdtesc             (),
    .o_dphy_rx_rxulpsesc             (f_rxulpsesc),
    .o_dphy_rx_rxtriggeresc          (),
    .o_dphy_rx_rxdataesc             (),
    .o_dphy_rx_rxvalidesc            (),
    .o_dphy_rx_errsoths              (f_errsot),
    .o_dphy_rx_errsotsynchs          (f_errsotsync),
    .o_dphy_rx_erresc                (f_erresc),
    .o_dphy_rx_errsyncesc            (),
    .o_dphy_rx_errcontrol            (f_errcontrol),
    .o_dphy_rx_sts_cl_state          (),
    .o_dphy_rx_sts_dl_state          (),
    .o_dphy_rx_sts_cl_abort_tgl      (),
    .o_dphy_rx_sts_errsoths_tgl      (),
    .o_dphy_rx_sts_errsotsynchs_tgl  (),
    .o_dphy_rx_sts_erreotsync_tgl    (),
    .o_dphy_rx_sts_hs_rx_timeout_tgl (),
    .o_dphy_rx_sts_erresc_tgl        (),
    .o_dphy_rx_sts_esc_timeout_tgl   (),
    .i_dphy_rx_afe_lp_dp             (r_lp_dp),
    .i_dphy_rx_afe_lp_dn             (r_lp_dn),
    .i_dphy_rx_afe_cl_lp_dp          (r_cl_lp_dp),
    .i_dphy_rx_afe_cl_lp_dn          (r_cl_lp_dn),
    .i_dphy_rx_afe_cl_hs_clk         (r_cl_hs_clk),
    .i_dphy_rx_afe_hs_bit            (r_hs_bit),
    .o_dphy_rx_afe_hs_en             (f_hs_en),
    .o_dphy_rx_afe_term_en           (f_term_en),
    .o_dphy_rx_afe_cl_hs_en          (f_cl_hs_en),
    .o_dphy_rx_afe_cl_term_en        (f_cl_term_en),
    .o_dphy_rx_afe_dly_tap           (),
    .i_dphy_rx_cfg_hs_settle_cyc     (cfg_hs_settle),
    .i_dphy_rx_cfg_clk_settle_cyc    (cfg_clk_settle),
    .i_dphy_rx_cfg_tinit_cyc         (cfg_tinit),
    .i_dphy_rx_cfg_hs_rx_timeout_cyc (C_HS_RX_TIMEOUT_CYC_RST),
    .i_dphy_rx_cfg_esc_timeout_cyc   (C_ESC_TIMEOUT_CYC_RST),
    .i_dphy_rx_cfg_eot_skip_bytes    (cfg_eot_skip),
    .i_dphy_rx_cfg_lane_map          (f_lane_map),
    .i_dphy_rx_cfg_lane_pol          ({NL{1'b0}})
  );

  // ------------------------------------------------------------------ PPI of ftel_dphy_rx into xrxss_np
  // +PPI_CORRUPT flips one bit of one byte on the way (negative test). Per lane, the bursts (runs of rxactivehs)
  // and the bytes of a burst (samples with rxvalidhs) are counted at the byte clock of ftel_dphy_rx, from 0; the
  // counts change after the edge, so the byte the controller takes at an edge sees the counts of the bytes before it.
  // +PPI_XFILL=1 (diagnosis only) gives 0 to the bits of rxdatahs that are X or Z: while rxvalidhs is 0 the PPI
  // leaves the data free, and ftel_dphy_rx has it unknown for the first byte clocks (data flip-flops without reset).
  int                 c_lane = -1, c_pkt = -1, c_byte = -1, c_bit = 0, c_events = 0, c_xfills = 0;
  bit                 c_xfill = 1'b0;
  int                 c_bursts [NL], c_bytes [NL];
  logic [NL-1:0]      c_act_q = '0;
  logic [NL-1:0][7:0] c_data;

  initial foreach (c_bursts[l]) begin
    c_bursts[l] = 0;
    c_bytes[l]  = 0;
  end

  function automatic bit c_hit(input int l);
    bit first = f_active[l] && !c_act_q[l];
    int burst = first ? c_bursts[l] : c_bursts[l] - 1;
    int idx   = first ? 0 : c_bytes[l];
    return l == c_lane && f_active[l] === 1'b1 && f_valid[l] === 1'b1 && burst == c_pkt && idx == c_byte;
  endfunction

  // always_comb, not assign: c_hit reads the counts, which are not its arguments
  always_comb
    for (int l = 0; l < NL; l++) begin
      c_data[l] = f_data[l] ^ (c_hit(l) ? 8'(1 << c_bit) : 8'h00);
      if (c_xfill)
        for (int b = 0; b < 8; b++) c_data[l][b] = (c_data[l][b] === 1'b1);
    end

  always @(posedge f_byteclk)
    for (int l = 0; l < NL; l++) begin
      if (c_xfill && $isunknown(f_data[l])) c_xfills++;
      if (c_hit(l)) begin
        c_events++;
        $display("TB CORRUPT: lane %0d packet %0d byte %0d bit %0d: %02x sent as %02x at %.3f ns", l, c_pkt, c_byte,
                 c_bit, f_data[l], c_data[l], $realtime);
      end
      if (f_active[l] && !c_act_q[l]) begin
        c_bursts[l] <= c_bursts[l] + 1;
        c_bytes[l]  <= (f_valid[l] === 1'b1) ? 1 : 0;
      end else if (f_active[l] && f_valid[l] === 1'b1) begin
        c_bytes[l] <= c_bytes[l] + 1;
      end
      c_act_q[l] <= f_active[l];
    end

  // +PPI_SOTSYNCERR: the burst it names keeps rxactivehs, loses rxsynchs and rxvalidhs, and gets errsotsynchs in the
  // cycle of rxsynchs, as ftel_dphy_rx gives a burst after a SoT sync error (HAS C8). Without it p_* are f_*.
  int            s_lane = -1, s_pkt = -1, s_events = 0;
  logic [NL-1:0] p_valid, p_sync, p_errsotsync;

  function automatic bit s_hit(input int l);
    bit first = f_active[l] && !c_act_q[l];
    int burst = first ? c_bursts[l] : c_bursts[l] - 1;
    return l == s_lane && f_active[l] === 1'b1 && burst == s_pkt;
  endfunction

  // always_comb, not assign: s_hit reads the counts, which are not its arguments
  always_comb
    for (int l = 0; l < NL; l++) begin
      p_valid[l]      = f_valid[l] && !s_hit(l);
      p_sync[l]       = f_sync[l] && !s_hit(l);
      p_errsotsync[l] = f_errsotsync[l] || (s_hit(l) && f_sync[l] === 1'b1);
    end

  always @(posedge f_byteclk)
    for (int l = 0; l < NL; l++) s_events += s_hit(l) && f_sync[l] === 1'b1;

  // +PPI_AMD_TIMING (diagnosis only) moves the start of each burst into xrxss_np toward AMD's D-PHY: ftel_dphy_rx
  // pulses rxsynchs in the cycle of the first payload byte (HAS C6) and raises rxactivehs some cycles earlier, AMD's
  // D-PHY pulses rxsynchs one cycle before the first byte, with rxactivehs. With 1 and 2, data, rxvalidhs and
  // rxactivehs go one byte clock later while rxsynchs and errsoths stay in place; 1 also raises rxactivehs only with
  // rxsynchs (a burst without sync then has no rxactivehs), 2 keeps it as ftel_dphy_rx drives it. 3 only raises
  // rxactivehs with rxsynchs and delays nothing. +PPI_ADAPTER takes rxactivehs from the gate of fpga/rtl/ instead.
  int                 amd_timing = 0;
  bit                 adapter = 1'b0;
  logic [NL-1:0][7:0] a_data, d_data;
  logic [NL-1:0]      a_valid, a_active, d_valid = '0, d_active = '0, a_seen = '0;
  wire  [NL-1:0]      g_active;

  always @(posedge f_byteclk) begin
    d_data   <= c_data;
    d_valid  <= p_valid;
    d_active <= f_active;
    for (int l = 0; l < NL; l++)
      if (!(f_active[l] || d_active[l])) a_seen[l] <= 1'b0;
      else if (p_sync[l])                a_seen[l] <= 1'b1;
  end

  always_comb
    for (int l = 0; l < NL; l++)
      if (amd_timing == 0) begin
        a_data[l]   = c_data[l];
        a_valid[l]  = p_valid[l];
        a_active[l] = adapter ? g_active[l] : f_active[l];
      end else if (amd_timing == 3) begin
        a_data[l]   = c_data[l];
        a_valid[l]  = p_valid[l];
        a_active[l] = f_active[l] && (a_seen[l] || p_sync[l]);
      end else begin
        a_data[l]   = d_data[l];
        a_valid[l]  = d_valid[l];
        a_active[l] = (f_active[l] || d_active[l]) && (amd_timing == 2 || a_seen[l] || p_sync[l]);
      end

  // The gate of the FPGA prototype on the PPI of ftel_dphy_rx, reset with it; checked at every byte clock against a
  // model of its rule: rxactivehs from the first rxsynchs of a burst to the end of the burst. The model clears with
  // the reset of ftel_dphy_rx, the gate two byte clocks later (its reset synchronizer), before any burst.
  m_ftel_ppi_act_gate #(.PARA_NUM_LANES(NL)) u_act_gate (
    .i_byte_clk   (f_byteclk),
    .i_byte_rst_n (f_rst_n),
    .i_rxactivehs (f_active),
    .i_rxsynchs   (p_sync),
    .o_rxactivehs (g_active)
  );

  logic [NL-1:0] r_seen = '0;
  int            g_cmp = 0, g_diff = 0;
  always @(posedge f_byteclk or negedge f_rst_n)
    if (!f_rst_n) r_seen <= '0;
    else          r_seen <= f_active & (p_sync | r_seen);
  always @(posedge f_byteclk)
    if (adapter && f_rst_n) begin
      g_cmp++;
      if (g_active !== (f_active & (p_sync | r_seen))) begin
        g_diff++;
        if (g_diff <= 5) $display("TB ADAPTER DIFF at %.3f ns: gate %b, model %b", $realtime, g_active,
                                  f_active & (p_sync | r_seen));
      end
    end

  // ------------------------------------------------------------------ R-F: AMD's CSI-2 receiver without PHY
  logic [7:0]  n_araddr, n_awaddr;
  logic [31:0] n_rdata, n_wdata;
  logic [3:0]  n_wstrb;
  logic [1:0]  n_bresp, n_rresp;
  logic        n_arready, n_arvalid, n_awready, n_awvalid, n_bready, n_bvalid, n_rready, n_rvalid, n_wready, n_wvalid;
  logic        n_irq;
  logic [39:0] n_tdata;
  logic [9:0]  n_tdest;
  logic [95:0] n_tuser;
  logic        n_tlast, n_tvalid;

  `define TN2B_NP(n) \
      .mipi_ppi_if_dl``n``_enable (np_dl_enable[n]), .mipi_ppi_if_dl``n``_errcontrol (f_errcontrol[n]), \
      .mipi_ppi_if_dl``n``_erresc (f_erresc[n]), .mipi_ppi_if_dl``n``_errsoths (f_errsot[n]), \
      .mipi_ppi_if_dl``n``_errsotsynchs (p_errsotsync[n]), .mipi_ppi_if_dl``n``_rxactivehs (a_active[n]), \
      .mipi_ppi_if_dl``n``_rxdatahs (a_data[n]), .mipi_ppi_if_dl``n``_rxsynchs (p_sync[n]), \
      .mipi_ppi_if_dl``n``_rxulpsesc (f_rxulpsesc[n]), .mipi_ppi_if_dl``n``_rxvalidhs (a_valid[n]), \
      .mipi_ppi_if_dl``n``_stopstate (f_stop[n]),
  xrxss_np u_xrxss_np (
    .lite_aclk (lite_clk), .lite_aresetn (rx_aresetn), .dphy_clk_200M (core_clk), .rxbyteclkhs_in (f_byteclk),
    .csirxss_csi_irq (n_irq), .video_aclk (vid_clk), .video_aresetn (rx_aresetn),
    .mipi_ppi_if_cl_enable (np_cl_enable), .mipi_ppi_if_cl_rxulpsclknot (f_cl_ulpsclknot),
    .mipi_ppi_if_cl_stopstate (f_cl_stop),
    `TN2B_NP(0) `TN2B_NP(1) `TN2B_NP(2) `TN2B_NP(3)
    .video_out_tdata (n_tdata), .video_out_tdest (n_tdest), .video_out_tlast (n_tlast), .video_out_tready (1'b1),
    .video_out_tuser (n_tuser), .video_out_tvalid (n_tvalid),
    .csirxss_s_axi_araddr (n_araddr), .csirxss_s_axi_arready (n_arready), .csirxss_s_axi_arvalid (n_arvalid),
    .csirxss_s_axi_awaddr (n_awaddr), .csirxss_s_axi_awready (n_awready), .csirxss_s_axi_awvalid (n_awvalid),
    .csirxss_s_axi_bready (n_bready), .csirxss_s_axi_bresp (n_bresp), .csirxss_s_axi_bvalid (n_bvalid),
    .csirxss_s_axi_rdata (n_rdata), .csirxss_s_axi_rready (n_rready), .csirxss_s_axi_rresp (n_rresp),
    .csirxss_s_axi_rvalid (n_rvalid), .csirxss_s_axi_wdata (n_wdata), .csirxss_s_axi_wready (n_wready),
    .csirxss_s_axi_wstrb (n_wstrb), .csirxss_s_axi_wvalid (n_wvalid)
  );
  `undef TN2B_NP

  axil_bfm #(.NAME("R-F"), .AW(8)) u_bus_f (
    .aclk (lite_clk), .aresetn (rx_aresetn), .awaddr (n_awaddr), .awvalid (n_awvalid), .awready (n_awready),
    .wdata (n_wdata), .wstrb (n_wstrb), .wvalid (n_wvalid), .wready (n_wready), .bresp (n_bresp), .bvalid (n_bvalid),
    .bready (n_bready), .araddr (n_araddr), .arvalid (n_arvalid), .arready (n_arready), .rdata (n_rdata),
    .rresp (n_rresp), .rvalid (n_rvalid), .rready (n_rready)
  );

  // ------------------------------------------------------------------ monitors
  axis_csv_mon #(.RX(1'b0)) u_ax_t (
    .aclk (tx_vid_clk), .en (mon_en), .tdata (g_tdata[39:0]), .tvalid (g_tvalid), .tready (g_tready),
    .tuser (g_tuser), .tlast (g_tlast), .tdest ({8'h00, g_tdest})
  );
  axis_csv_mon #(.RX(1'b1)) u_ax_x (
    .aclk (vid_clk), .en (mon_en), .tdata (x_tdata), .tvalid (x_tvalid), .tready (1'b1), .tuser (x_tuser),
    .tlast (x_tlast), .tdest (x_tdest)
  );
  axis_csv_mon #(.RX(1'b1)) u_ax_f (
    .aclk (vid_clk), .en (mon_en), .tdata (n_tdata), .tvalid (n_tvalid), .tready (1'b1), .tuser (n_tuser),
    .tlast (n_tlast), .tdest (n_tdest)
  );

  ppi_csv_mon #(.NL(NL)) u_mon_x (
    .clk (x_byteclk), .en (mon_en), .data (x_data), .valid (x_valid), .active (x_active), .sync (x_sync),
    .errsot (x_errsot), .errsotsync (x_errsotsync), .stop (x_stop), .cl_stop (x_cl_stop)
  );
  ppi_csv_mon #(.NL(NL)) u_mon_f (
    .clk (f_byteclk), .en (mon_en), .data (a_data), .valid (a_valid), .active (a_active), .sync (p_sync),
    .errsot (f_errsot), .errsotsync (p_errsotsync), .stop (f_stop), .cl_stop (f_cl_stop)
  );
  // TX side: a byte moves when txrequesths and txreadyhs are High at the edge; a burst is a run of txrequesths.
  ppi_csv_mon #(.NL(NL)) u_mon_t (
    .clk (t_byteclk), .en (mon_en), .data (tp_data), .valid (tp_req & tp_ready), .active (tp_req),
    .sync ('0), .errsot ('0), .errsotsync ('0), .stop (~tp_req), .cl_stop (1'b0)
  );

  // ------------------------------------------------------------------ register sequences
  task automatic rx_rd(input int w, input logic [7:0] a, output logic [31:0] d);
    if (w == 0) u_bus_x.rd(a, d);
    else        u_bus_f.rd(a, d);
  endtask

  task automatic rx_wr(input int w, input logic [7:0] a, input logic [31:0] d);
    if (w == 0) u_bus_x.wr(a, d);
    else        u_bus_f.wr(a, d);
  endtask

  task automatic rx_poll(input int w, input logic [7:0] a, input logic [31:0] mask, input logic [31:0] want,
                         input int max_reads, output bit ok);
    if (w == 0) u_bus_x.poll(a, mask, want, max_reads, ok);
    else        u_bus_f.poll(a, mask, want, max_reads, ok);
  endtask

  // XCsiSs_Reset, XCsiSs_Configure (active lanes, interrupt mask 0) and XCsiSs_Activate of AMD's driver, as AMD's
  // camera example calls them (EnableCSI): soft reset, wait until CSR[0] (reset in progress or core disabled) is 0,
  // clear it; soft reset, wait, active lanes, clear; global interrupt enable, core enable.
  real t_rx_cfg [2] = '{-1.0, -1.0};
  bit  rx_reset_ok [2];
  task automatic rx_configure(input int w, input int lanes);
    logic [31:0] d;
    bit          ok;
    t_rx_cfg[w] = $realtime;
    rx_rd(w, R_CCR, d);
    rx_rd(w, R_PCR, d);
    rx_rd(w, R_CCR, d);
    rx_wr(w, R_CCR, d | 32'h2);
    rx_poll(w, R_CSR, 32'h1, 32'h0, 200, ok);
    rx_reset_ok[w] = ok;
    rx_rd(w, R_CCR, d);
    rx_wr(w, R_CCR, d & ~32'h2);
    rx_rd(w, R_CCR, d);
    rx_wr(w, R_CCR, d | 32'h2);
    rx_poll(w, R_CSR, 32'h1, 32'h0, 200, ok);
    rx_reset_ok[w] &= ok;
    rx_rd(w, R_PCR, d);
    rx_wr(w, R_PCR, (d & ~32'h3) | 32'(lanes - 1));
    rx_rd(w, R_CCR, d);
    rx_wr(w, R_CCR, d & ~32'h2);
    rx_wr(w, R_GIER, 32'h1);
    rx_rd(w, R_CCR, d);
    rx_wr(w, R_CCR, d | 32'h1);
    rx_rd(w, R_PCR, d);
  endtask

  // As AMD's example of the TX Subsystem (and the driver for the active lanes): CCR = 1 is core enable with CCR[4]
  // = 0, the continuous clock; then the example waits until CCR[2], core ready, is 1.
  real t_tx_enable = -1.0;
  bit  tx_ready_ok = 1'b0;
  task automatic tx_configure(input int lanes);
    logic [31:0] d;
    u_bus_t.rd(R_CCR, d);
    u_bus_t.rd(R_PCR, d);
    u_bus_t.wr(R_PCR, (d & ~32'h3) | 32'(lanes - 1));
    u_bus_t.wr(R_GIER, 32'h1);
    u_bus_t.wr(R_CCR, 32'h1);
    t_tx_enable = $realtime;
    u_bus_t.poll(R_CCR, 32'h4, 32'h4, 200, tx_ready_ok);
    u_bus_t.rd(R_PCR, d);
  endtask

  // One "TB REG <subsystem> <offset> <value>" line per register, read at the end of the run.
  task automatic report_regs();
    logic [31:0] d;
    string       nm [2] = '{"R-X", "R-F"};
    logic [7:0]  regs [$] = '{R_CCR, R_PCR, R_CSR, R_GIER, R_ISR, R_IER, R_CLKINFR, R_VC0INF1, R_VC0INF2};
    logic [7:0]  tregs [3] = '{R_CCR, R_PCR, R_ISR};
    for (int l = 0; l < NL; l++) regs.push_back(R_L0INFR + 8'(4 * l));
    for (int w = 0; w < 2; w++)
      foreach (regs[i]) begin
        rx_rd(w, regs[i], d);
        $display("TB REG %s 0x%02h 0x%08h", nm[w], regs[i], d);
      end
    foreach (tregs[i]) begin
      u_bus_t.rd(tregs[i], d);
      $display("TB REG TX 0x%02h 0x%08h", tregs[i], d);
    end
  endtask

  // ------------------------------------------------------------------ sequence
  string  outdir = ".", pattern = "counter", sel;
  real    rate = 1440.0, ui;
  int     frames = 2, width = 640, height = 16, line_gap = 0, frame_gap = 0, lanes_active = NL, timeout_us = 4000;
  int     corrupt [$], v_i, v_ok, frames_fd = 0;
  bit     rx_late = 1'b0, stream_toggle = 1'b0, vcd_on = 1'b0, toggle_ready_ok = 1'b0;
  real    t_tinit = -1.0, t_finit = -1.0, t_first_beat = -1.0, t_last_beat = -1.0;
  real    t_cl_req_on = -1.0, t_hs_x = -1.0, t_hs_f = -1.0;

  function automatic void parse_list(input string s, ref int q [$]);
    int start = 0, v;
    q = {};
    for (int i = 0; i <= s.len(); i++)
      if (i == s.len() || s[i] == ",") begin
        if (i > start && $sscanf(s.substr(start, i - 1), "%d", v) == 1) q.push_back(v);
        start = i + 1;
      end
  endfunction

  initial begin : p_watchdog
    #1;
    v_ok = $value$plusargs("TIMEOUT_US=%d", timeout_us);
    #(real'(timeout_us) * 1000.0);
    $display("TB TIMEOUT at %.3f us", $realtime / 1000.0);
    finish_run(1'b1);
  end

  // When the TX controller first requests the HS clock, and when the clock lane of each receiver first leaves stop
  // state once its D-PHY is up (stopstate is 0 until then); the first beat the TX takes.
  initial begin : p_hs_times
    fork
      begin wait (t_cl_req === 1'b1); t_cl_req_on = $realtime; end
      begin wait (x_cl_stop === 1'b1); wait (x_cl_stop === 1'b0); t_hs_x = $realtime; end
      begin wait (f_cl_stop === 1'b1); wait (f_cl_stop === 1'b0); t_hs_f = $realtime; end
    join
  end
  always @(posedge tx_vid_clk) if (t_first_beat < 0.0 && g_tvalid && g_tready) t_first_beat = $realtime;

  task automatic finish_run(input bit timeout);
    u_ax_t.close();
    u_ax_x.close();
    u_ax_f.close();
    u_mon_x.close();
    u_mon_f.close();
    u_mon_t.close();
    if (frames_fd != 0) $fclose(frames_fd);
    if (vcd_on) $dumpflush;
    u_afe.report();
    $display("TB FRONT END CHECK: LP outputs of AMD's buffers and of the buffers of ftel_dphy_rx differ at %0d of %0d changes",
             fe_diffs, fe_events);
    $display("TB AXIS tx: beats %0d, lines %0d, frames %0d", u_ax_t.n_beats, u_ax_t.n_lines, u_ax_t.n_frames);
    $display("TB AXIS xil: beats %0d, lines %0d, frames %0d", u_ax_x.n_beats, u_ax_x.n_lines, u_ax_x.n_frames);
    $display("TB AXIS ftel: beats %0d, lines %0d, frames %0d", u_ax_f.n_beats, u_ax_f.n_lines, u_ax_f.n_frames);
    $display("TB TX: init_done %.3f us, enabled %.3f us (core ready %s), first beat %.3f us, HS clock requested %.3f us, seen by R-X %.3f us, by R-F %.3f us, %0d frames, %0d lines sent, last beat %.3f us",
             t_tinit / 1000.0, t_tx_enable / 1000.0, tx_ready_ok ? string'("reached") : string'("NOT reached"),
             t_first_beat / 1000.0, t_cl_req_on / 1000.0, t_hs_x / 1000.0, t_hs_f / 1000.0, u_gen.n_frames,
             u_gen.n_lines, t_last_beat / 1000.0);
    if (stream_toggle)
      $display("TB TX TOGGLE: core ready after the second enable %s",
               toggle_ready_ok ? string'("reached") : string'("NOT reached"));
    $display("TB RX CFG: R-X set up at %.3f us (soft reset done %s), R-F set up at %.3f us (soft reset done %s)",
             t_rx_cfg[0] / 1000.0, rx_reset_ok[0] ? string'("reached") : string'("NOT reached"),
             t_rx_cfg[1] / 1000.0, rx_reset_ok[1] ? string'("reached") : string'("NOT reached"));
    if (c_lane >= 0) $display("TB CORRUPT: %0d bytes flipped", c_events);
    if (adapter) $display("TB ADAPTER CHECK: comparisons %0d, differences %0d", g_cmp, g_diff);
    if (s_lane >= 0)
      $display("TB SOTSYNCERR: lane %0d packet %0d: rxsynchs and rxvalidhs removed, errsotsynchs in place of rxsynchs, %0d events",
               s_lane, s_pkt, s_events);
    if (c_xfill) $display("TB XFILL: %0d bytes with X or Z given 0 at the byte clock edges", c_xfills);
    $display("TB AXIL: errors TX %0d, R-X %0d, R-F %0d", u_bus_t.errors, u_bus_x.errors, u_bus_f.errors);
    $display("TB DONE %s: NL %0d, rate %.2f Mb/s (UI %.3f ns), %0d frames of %0dx%0d sent, TX init_done %.3f us, ftel init_done %.3f us",
             timeout ? "TIMEOUT" : "OK", NL, 1000.0 / ui, ui, u_gen.n_frames, width, height, t_tinit / 1000.0,
             t_finit / 1000.0);
    $finish;
  endtask

  // Waits until both receivers have given want lines, or max_us more, whichever comes first.
  task automatic drain(input int want, input real max_us);
    real t0 = $realtime;
    while ((u_ax_x.n_lines < want || u_ax_f.n_lines < want) && $realtime - t0 < max_us * 1000.0) #100;
    #2000;
  endtask

  // With +RX_LATE=1 the receivers run from reset (CCR is 1 after reset), give part of frame 0 and may lose lines at
  // their set-up, so the number of lines they give is not known: waits until neither gave a line for 30 us (several
  // line times at every rate of the plan), or max_us more.
  task automatic drain_quiet(input real max_us);
    real t0 = $realtime;
    int  nx, nf;
    do begin
      nx = u_ax_x.n_lines;
      nf = u_ax_f.n_lines;
      #30000;
    end while ((u_ax_x.n_lines != nx || u_ax_f.n_lines != nf) && $realtime - t0 < max_us * 1000.0);
    #2000;
  endtask

  initial begin : p_main
    v_ok = $value$plusargs("OUTDIR=%s", outdir);
    v_ok = $value$plusargs("RATE=%f", rate);
    v_ok = $value$plusargs("FRAMES=%d", frames);
    v_ok = $value$plusargs("WIDTH=%d", width);
    v_ok = $value$plusargs("HEIGHT=%d", height);
    v_ok = $value$plusargs("PATTERN=%s", pattern);
    v_ok = $value$plusargs("LINE_GAP=%d", line_gap);
    v_ok = $value$plusargs("FRAME_GAP=%d", frame_gap);
    v_ok = $value$plusargs("LANES_ACTIVE=%d", lanes_active);
    if ($value$plusargs("RX_LATE=%d", v_i)) rx_late = (v_i != 0);
    if ($value$plusargs("STREAM_TOGGLE=%d", v_i)) stream_toggle = (v_i != 0);
    v_ok = $value$plusargs("CORE_HALF=%f", core_half);
    v_ok = $value$plusargs("TX_CORE_HALF=%f", tx_core_half);
    if ($value$plusargs("AFE=%s", sel)) begin
      if (sel != "xil" && sel != "model") $fatal(1, "TB: +AFE=%s, expected xil or model", sel);
      afe_xil = (sel == "xil");
    end
    if ($value$plusargs("VCD=%d", v_i)) vcd_on = (v_i != 0);
    if ($value$plusargs("NEG_FRONT=%d", v_i)) neg_front = (v_i != 0);
    if ($value$plusargs("PPI_XFILL=%d", v_i)) c_xfill = (v_i != 0);
    v_ok = $value$plusargs("PPI_AMD_TIMING=%d", amd_timing);
    if (amd_timing < 0 || amd_timing > 3) $fatal(1, "TB: +PPI_AMD_TIMING=%0d, expected 0 to 3", amd_timing);
    if ($value$plusargs("PPI_ADAPTER=%d", v_i)) adapter = (v_i != 0);
    if (adapter && amd_timing != 0) $fatal(1, "TB: +PPI_ADAPTER=1 with +PPI_AMD_TIMING=%0d", amd_timing);
    if ($value$plusargs("PPI_SOTSYNCERR=%s", sel)) begin
      parse_list(sel, corrupt);
      if (corrupt.size() != 2) $fatal(1, "TB: +PPI_SOTSYNCERR=%s, expected <lane>,<packet>", sel);
      s_lane = corrupt[0];
      s_pkt  = corrupt[1];
      corrupt = {};
    end
    if ($value$plusargs("PPI_CORRUPT=%s", sel)) begin
      parse_list(sel, corrupt);
      if (corrupt.size() != 4) $fatal(1, "TB: +PPI_CORRUPT=%s, expected <lane>,<packet>,<byte>,<bit>", sel);
      c_lane = corrupt[0];
      c_pkt  = corrupt[1];
      c_byte = corrupt[2];
      c_bit  = corrupt[3];
    end
    if ($value$plusargs("HS_SETTLE=%d", v_i)) cfg_hs_settle = v_i;
    if ($value$plusargs("CLK_SETTLE=%d", v_i)) cfg_clk_settle = v_i;
    if ($value$plusargs("EOT_SKIP=%d", v_i)) cfg_eot_skip = v_i;
    if ($value$plusargs("TINIT=%d", v_i)) cfg_tinit = v_i;
    if (width % 4 != 0 || width < 4) $fatal(1, "TB: +WIDTH=%0d, expected a multiple of 4 pixels", width);
    if (lanes_active < 1 || lanes_active > NL) $fatal(1, "TB: +LANES_ACTIVE=%0d, expected 1..%0d", lanes_active, NL);
    if (stream_toggle && frames < 2) $fatal(1, "TB: +STREAM_TOGGLE=1 needs at least 2 frames");

    ui = 2.0 * (real'($rtoi(1000.0 / rate * 500.0 + 0.5)) / 1000.0);
    u_afe.ui        = ui;
    u_gen.width     = width;
    u_gen.height    = height;
    u_gen.pattern   = pattern;
    u_gen.line_gap  = line_gap;
    u_gen.frame_gap = frame_gap;
    frames_fd       = $fopen({outdir, "/frames.txt"}, "w");
    u_gen.frames_fd = frames_fd;
    u_ax_t.open({outdir, "/tx_axis.csv"});
    u_ax_x.open({outdir, "/xil_axis.csv"});
    u_ax_f.open({outdir, "/ftel_axis.csv"});
    u_mon_x.open({outdir, "/xil_ppi.csv"});
    u_mon_f.open({outdir, "/ftel_ppi.csv"});
    u_mon_t.open({outdir, "/tx_ppi.csv"});
    if (vcd_on) begin
      $dumpfile({outdir, "/tn2b.vcd"});
      $dumpvars(1, tb_exp2b);
    end
    // string'(): ?: on two text literals pads the shorter one with spaces
    $display("TB START: NL %0d, rate %.2f Mb/s (UI %.3f ns), %0d frames of %0dx%0d, pattern %s, line gap %0d, frame gap %0d, active lanes %0d, receivers set up %s%s",
             NL, 1000.0 / ui, ui, frames, width, height, pattern, line_gap, frame_gap, lanes_active,
             rx_late ? string'("late, during frame 0") : string'("before the TX starts"),
             stream_toggle ? string'(", stream off and on after frame 0") : string'(""));
    $display("TB TX CFG: core clock period %.5f ns (receivers %.5f ns), corrupt lane %0d packet %0d byte %0d bit %0d",
             2.0 * tx_core_half, 2.0 * core_half, c_lane, c_pkt, c_byte, c_bit);
    if (c_xfill || amd_timing != 0)
      $display("TB DIAG: on the PPI into xrxss_np, X fill %0d, AMD timing mode %0d (diagnosis only)", c_xfill,
               amd_timing);
    if (adapter) $display("TB ADAPTER: rxactivehs into xrxss_np from m_ftel_ppi_act_gate (fpga/rtl/)");
    $display("TB FRONT END: ftel_dphy_rx behind %s%s",
             afe_xil ? string'("IBUFDS_DPHY (SIM_DEVICE VERSAL_PREMIUM), the input buffer of AMD's receiver") :
                       string'("afe_model"),
             neg_front ? string'("; negative test: pull strength at its buffers during HS") : string'(""));
    $display("TB FTEL CFG: hs_settle_cyc %0d, clk_settle_cyc %0d, eot_skip_bytes %0d, tinit_cyc %0d",
             cfg_hs_settle, cfg_clk_settle, cfg_eot_skip, cfg_tinit);

    #100;
    tx_aresetn = 1'b1;
    rx_aresetn = 1'b1;
    f_rst_n    = 1'b1;
    mon_en     = 1'b1;
    fork
      begin
        wait (f_init_done === 1'b1);
        t_finit = $realtime;
      end
      begin
        #1000;
        if (!rx_late)
          fork
            rx_configure(0, lanes_active);
            rx_configure(1, lanes_active);
          join
      end
      begin
        wait (t_init_done === 1'b1);
        t_tinit = $realtime;
      end
    join
    #1000;
    tx_configure(lanes_active);
    // No wait for the clock lane: without video the TX kept it in LP (still at 3.4 ms in the first E2b-1 of
    // 2026-10-23, which waited for it); p_hs_times records when it starts.
    @(posedge tx_vid_clk);
    fork
      begin
        for (int f = 0; f < frames; f++) begin
          u_gen.send_frame(f);
          if (stream_toggle && f == 0) begin
            u_gen.stop();
            drain(height, 100.0);
            u_bus_t.wr(R_CCR, 32'h0);
            #20000;
            u_bus_t.wr(R_CCR, 32'h1);
            u_bus_t.poll(R_CCR, 32'h4, 32'h4, 200, toggle_ready_ok);
            @(posedge tx_vid_clk);
          end
        end
        u_gen.stop();
        t_last_beat = $realtime;
      end
      begin
        if (rx_late) begin
          wait (u_gen.n_lines >= height / 2);
          fork
            rx_configure(0, lanes_active);
            rx_configure(1, lanes_active);
          join
        end
      end
    join
    if (rx_late || s_lane >= 0) drain_quiet(400.0);   // R-F gives less than the frames sent
    else                        drain(frames * height, 200.0);
    report_regs();
    finish_run(1'b0);
  end
