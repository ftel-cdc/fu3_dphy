    .clkoutphy_out (), .pll_lock_out (), .txclkesc_out (), .system_rst_out (), .mmcm_lock_out (), .interrupt (t_irq),
    .s_axi_araddr (t_araddr), .s_axi_arready (t_arready), .s_axi_arvalid (t_arvalid), .s_axi_awaddr (t_awaddr),
    .s_axi_awready (t_awready), .s_axi_awvalid (t_awvalid), .s_axi_bready (t_bready), .s_axi_bresp (t_bresp),
    .s_axi_bvalid (t_bvalid), .s_axi_rdata (t_rdata), .s_axi_rready (t_rready), .s_axi_rresp (t_rresp),
    .s_axi_rvalid (t_rvalid), .s_axi_wdata (t_wdata), .s_axi_wready (t_wready), .s_axi_wstrb (t_wstrb),
    .s_axi_wvalid (t_wvalid),
