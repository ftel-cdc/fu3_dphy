    .s_axis_tready (g_tready), .s_axis_tuser (g_tuser), .s_axis_tvalid (g_tvalid),
    .mipi_phy_if_clk_n (t_clk_n), .mipi_phy_if_clk_p (t_clk_p), .mipi_phy_if_data_n (t_d_n), .mipi_phy_if_data_p (t_d_p)
  );

  axil_bfm #(.NAME("TX"), .AW(8)) u_bus_t (
    .aclk (tx_vid_clk), .aresetn (tx_aresetn), .awaddr (t_awaddr), .awvalid (t_awvalid), .awready (t_awready),
    .wdata (t_wdata), .wstrb (t_wstrb), .wvalid (t_wvalid), .wready (t_wready), .bresp (t_bresp), .bvalid (t_bvalid),
    .bready (t_bready), .araddr (t_araddr), .arvalid (t_arvalid), .arready (t_arready), .rdata (t_rdata),
    .rresp (t_rresp), .rvalid (t_rvalid), .rready (t_rready)
