// TN2b testbench (fpga/PLAN_TN2B.md). Synthetic RAW10 frames (axis_vid_gen, plan §2) go into AMD's CSI-2 TX
// Subsystem 2.2 (module xtxss, generated by exp2b.tcl); its pads feed two complete CSI-2 receivers:
// - R-X: AMD's CSI-2 RX Subsystem 6.0 with its D-PHY (xrxss), configured as the build of the board, with the PPI
//   monitor port;
// - R-F: ftel_dphy_rx (the ASIC RTL of logical/, unchanged) behind IBUFDS_DPHY (default) or afe_model (+AFE=model),
//   as in TN1, and AMD's CSI-2 RX Subsystem 6.0 without PHY (xrxss_np) on its PPI (wiring of plan §4.3).
// The front end of ftel_dphy_rx is the code of tb_exp1.sv; the front-end check is that code with the path to AMD's
// buffers changed to the D-PHY inside xrxss; the instance of the wrap is that code with the enables, ULPS and
// escape errors wired to xrxss_np (tn2b_evidence.py, check copy).
// The subsystems are programmed through axil_bfm: the receivers in the order of AMD's driver (soft reset, wait,
// active lanes, global interrupt, enable), the TX as AMD's example of the TX Subsystem does it (active lanes as the
// driver, then CCR = 1: core enable with CCR[4] = 0, the continuous clock, then a wait for CCR[2], core ready).
// The video starts right after core ready, as in that example: nothing waits for the clock lane of the TX, and the
// TB TX line tells when its controller requested HS and when each receiver saw it.
// By default the receivers are set up before the TX starts, as in AMD's camera example, so their byte clocks are
// not running yet. Clocks: core_clk 200 MHz (dphy_clk_200M of both receivers, core_clk of ftel_dphy_rx), the TX's
// own 200 MHz core clock, s_axis_aclk of the TX 200 MHz (also its AXI4-Lite clock, as in AMD's example), video_aclk
// of the receivers 250 MHz and lite_aclk 50 MHz (as the build of the board).
// Files in +OUTDIR: frames.txt (frames sent), tx_axis.csv (s_axis of the TX), xil_axis.csv / ftel_axis.csv
// (video_out of R-X / R-F), xil_ppi.csv (PPI monitor port of R-X), ftel_ppi.csv (the PPI into xrxss_np, after
// +PPI_CORRUPT, +PPI_XFILL, +PPI_SOTSYNCERR and +PPI_AMD_TIMING or the gate of +PPI_ADAPTER), tx_ppi.csv (the PPI
// inside xtxss, from its controller to its D-PHY), tn2b.vcd with +VCD=1.
// Plusargs, all optional:
//   +OUTDIR=<dir> +RATE=<Mb/s>         the rate of the build (default 1440)
//   +FRAMES=<n> +WIDTH=<px> +HEIGHT=<lines> +PATTERN=counter|prbs|synclike +LINE_GAP=<clk> +FRAME_GAP=<clk>
//                                      frames of axis_vid_gen (default 2 frames of 640 x 16, counter, no gaps)
//   +LANES_ACTIVE=<n>                  active lanes of the three subsystems (default 4)
//   +RX_LATE=1                         set up both receivers together once half of frame 0 is sent
//   +STREAM_TOGGLE=1                   disable the TX after frame 0 and enable it again (stream off and on)
//   +CORE_HALF=<ns> +TX_CORE_HALF=<ns> half periods of core_clk and of the TX's core clock (default 2.5)
//   +PPI_CORRUPT=<lane>,<packet>,<byte>,<bit>   flip that bit on the PPI into xrxss_np (negative test); packet
//                                      counts the bursts of that lane from 0, byte the bytes of the burst from 0
//   +PPI_XFILL=1                       diagnosis only: bits of rxdatahs into xrxss_np that are X or Z become 0
//   +PPI_AMD_TIMING=1|2|3              diagnosis only: the start of each burst into xrxss_np moved toward AMD's
//                                      D-PHY (1: rxsynchs before the first byte and rxactivehs from rxsynchs, as
//                                      AMD's D-PHY; 2: rxsynchs before the first byte only; 3: rxactivehs from
//                                      rxsynchs only, rxsynchs still with the first byte)
//   +PPI_ADAPTER=1                     rxactivehs into xrxss_np from m_ftel_ppi_act_gate (fpga/rtl/), the gate of
//                                      the FPGA prototype (fpga/PLAN_TN2B_GATE.md), checked against a model here
//                                      at every byte clock; not with +PPI_AMD_TIMING
//   +PPI_SOTSYNCERR=<lane>,<packet>    in that burst of that lane (counted as for +PPI_CORRUPT), no rxsynchs and no
//                                      rxvalidhs, errsotsynchs instead in the cycle of rxsynchs: the PPI of
//                                      ftel_dphy_rx after a SoT sync error (HAS C8); the run then ends when no
//                                      receiver has given a line for 30 us
//   +NEG_FRONT=1                       during HS the buffers of ftel_dphy_rx see pull strength (negative test)
//   +AFE=xil|model +HS_SETTLE= +CLK_SETTLE= +EOT_SKIP= +TINIT=   as in tb_exp1.sv
//   +VCD=1 (needs a build with debug typical)  +TIMEOUT_US=<us> (default 4000)
