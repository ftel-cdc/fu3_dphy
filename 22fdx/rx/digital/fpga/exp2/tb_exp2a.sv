// TN2a testbench (fpga/PLAN_TN2A.md). AMD's D-PHY TX (mipi_dphy 4.3, MASTER, generated by exp2.tcl as module
// xtx), driven at its PPI by ppi_tx_drv, sends dummy data to the two receivers of TN1 (+SRC=tx, default). With
// +SRC=gen the TN1 line generator drives the pads instead and the TX stays in reset; that mode checks the
// decoder of the pads against the generator's own truth.
// - AMD's D-PHY RX: mipi_dphy 4.3, SLAVE, module xrx, as in TN1.
// - ftel_dphy_rx: the ASIC RTL of logical/, unchanged, behind IBUFDS_DPHY (default) or afe_model (+AFE=model),
//   as in TN1. The front end of ftel_dphy_rx, the front-end check and the instance of the wrap are the code
//   of tb_exp1.sv, unchanged (tn2a_evidence.py, check copy). The comparisons of the front-end check up to
//   2.5 ps are reported apart and not counted (p_fe_start).
// - pad_truth decodes the pads into truth.txt (the truth file of fpga/tools/csi2_dump.py bursts), checks the
//   bytes at the pads against the bytes given to the line, and measures the timing of the line.
// - The TX has its own core clock (+TX_CORE_HALF), the receivers core_clk (+CORE_HALF). The XSIM models of the
//   TX's clocking give the line its nominal rate whatever the period of that clock (plan step 0: 100 ppm slower
//   gave the same byte clock and pads to the ps), so +CORE_HALF moves core_clk against the line, as in TN1.
// Each PPI is written as an ILA-style CSV (ppi_csv_mon); expected.txt lists the bytes given to the line, per
// lane and burst. Parameter NL = lanes (1, 2 or 4), set at elaboration. Plusargs, all optional:
//   +OUTDIR=<dir>                 truth.txt, expected.txt, xil_ppi.csv, ftel_ppi.csv; truth_gen.txt with
//                                 +SRC=gen; tn2a.vcd with +VCD=1 (default .)
//   +RATE=<Mb/s>                  line rate, the one xtx and xrx were built for (default 1440)
//   +SRC=tx|gen                   source of the pads: AMD's TX (default) or the TN1 line generator
//   +LENS=<n,n,...> +REPEAT=<n> +PATTERN=counter|prbs9|synclike +UNEVEN=1    payloads, as in tb_exp1.sv
//   +GAP_NS=<ns>                  wait after every lane is back in stopstate, before the next burst (default 150)
//   +READY0=1                     every lane follows txreadyhs of lane 0 (see ppi_tx_drv)
//   +TX_CORE_HALF=<ns>            half period of the TX's core clock (default 2.5)
//   +CORE_HALF=<ns>               half period of core_clk of both receivers (default 2.5); 2.501 or 2.499
//                                 (400 ppm) lets core_clk drift against the line, so LP-11 meets it at every phase
//   +TX_CORRUPT=<lane>,<burst>,<byte>   send that byte inverted, keep the original as expected (negative test)
//   +NEG_FRONT=1                  during HS the buffers of ftel_dphy_rx see pull strength (negative test of the
//                                 front-end check)
//   +TXLOG=<n>                    print the PPI handshake of the TX until <n> bursts are done
//   +VCD=1                        tn2a.vcd with the signals of this module (needs a build with debug typical)
//   +HS_SETTLE= +CLK_SETTLE= +EOT_SKIP= +TINIT=   run-time fields of ftel_dphy_rx (default: reset values)
//   +FTEL=0  +AFE=xil|model  +AFE_NOISE=1         as in tb_exp1.sv
//   +TIMEOUT_US=<us>              simulation limit (default 2000)
//   With +SRC=gen, also the line knobs of tb_exp1.sv: +TLPX= +THS_PREPARE= +THS_ZERO= +THS_TRAIL= +THS_EXIT=
//   +TCLK_PREPARE= +TCLK_ZERO= +PREP= +ZERO= +TRAIL= +EXIT= +LPX= +SKEW0..3= +CLK_SKEW= +TRAIL_JITTER=
//   +EOT_JUNK= +SEED=
`timescale 1ns/1ps
module tb_exp2a;
  import ftel_dphy_rx_pkg::*;
  import ftel_dphy_rx_config_pkg::*;

  parameter int NL = 4;
  localparam int SELW = f_lane_sel_w(NL);

  typedef byte unsigned bq_t [$];

  // ------------------------------------------------------------------ clocks, resets, control
  logic core_clk    = 1'b0;
  logic tx_core_clk = 1'b0;
  logic xrst        = 1'b1;
  logic trst        = 1'b1;
  logic f_rst_n     = 1'b0;
  logic mon_en      = 1'b0;
  real  core_half    = 2.5;
  real  tx_core_half = 2.5;
  always #(core_half) core_clk = ~core_clk;            // 200 MHz for both receivers
  always #(tx_core_half) tx_core_clk = ~tx_core_clk;   // 200 MHz of the TX, its own oscillator (see the header)

  // ------------------------------------------------------------------ line generator (+SRC=gen)
  logic          g_clk_p, g_clk_n;
  logic [NL-1:0] g_d_p, g_d_n;
  logic [NL-1:0] hs_truth;
  logic          cl_hs_truth;

  dphy_line_gen #(.NL(NL)) u_gen (
    .clk_p       (g_clk_p),
    .clk_n       (g_clk_n),
    .d_p         (g_d_p),
    .d_n         (g_d_n),
    .hs_truth    (hs_truth),
    .cl_hs_truth (cl_hs_truth)
  );

  // ------------------------------------------------------------------ AMD's transmitter (+SRC=tx)
  wire                 t_clk_p, t_clk_n;
  wire  [NL-1:0]       t_d_p, t_d_n;
  logic                t_byteclk, t_init_done, t_cl_stop, t_cl_active, t_cl_req;
  logic [NL-1:0][7:0]  t_data;
  logic [NL-1:0]       t_req, t_ready, t_stop;

  // Common ports and the ports of data lane n of xtx: PPI from ppi_tx_drv; escape mode and ULPS unused.
  `define TN2_XTX_COMMON \
      .core_clk (tx_core_clk), .core_rst (trst), .txclkesc_out (), .txbyteclkhs (t_byteclk), .clkoutphy_out (), \
      .pll_lock_out (), .mmcm_lock_out (), .system_rst_out (), .init_done (t_init_done), \
      .cl_txclkactivehs (t_cl_active), .cl_txrequesths (t_cl_req), .cl_stopstate (t_cl_stop), .cl_enable (1'b1), \
      .cl_txulpsclk (1'b0), .cl_txulpsexit (1'b0), .cl_ulpsactivenot (),
  `define TN2_XTX_DL(n) \
      .dl``n``_txdatahs (t_data[n]), .dl``n``_txrequesths (t_req[n]), .dl``n``_txreadyhs (t_ready[n]), \
      .dl``n``_forcetxstopmode (1'b0), .dl``n``_stopstate (t_stop[n]), .dl``n``_enable (1'b1), \
      .dl``n``_txrequestesc (1'b0), .dl``n``_txlpdtesc (1'b0), .dl``n``_txulpsexit (1'b0), \
      .dl``n``_ulpsactivenot (), .dl``n``_txulpsesc (1'b0), .dl``n``_txtriggeresc (4'b0000), \
      .dl``n``_txdataesc (8'h00), .dl``n``_txvalidesc (1'b0), .dl``n``_txreadyesc (),
  if (NL == 4) begin : g_t
    xtx u_xtx (`TN2_XTX_COMMON `TN2_XTX_DL(0) `TN2_XTX_DL(1) `TN2_XTX_DL(2) `TN2_XTX_DL(3)
               .clk_txp (t_clk_p), .clk_txn (t_clk_n), .data_txp (t_d_p), .data_txn (t_d_n));
  end else if (NL == 2) begin : g_t
    xtx u_xtx (`TN2_XTX_COMMON `TN2_XTX_DL(0) `TN2_XTX_DL(1)
               .clk_txp (t_clk_p), .clk_txn (t_clk_n), .data_txp (t_d_p), .data_txn (t_d_n));
  end else begin : g_t
    xtx u_xtx (`TN2_XTX_COMMON `TN2_XTX_DL(0)
               .clk_txp (t_clk_p), .clk_txn (t_clk_n), .data_txp (t_d_p), .data_txn (t_d_n));
  end
  `undef TN2_XTX_COMMON
  `undef TN2_XTX_DL

  ppi_tx_drv #(.NL(NL)) u_drv (
    .byteclk          (t_byteclk),
    .cl_txrequesths   (t_cl_req),
    .cl_txclkactivehs (t_cl_active),
    .cl_stopstate     (t_cl_stop),
    .txrequesths      (t_req),
    .txreadyhs        (t_ready),
    .txdatahs         (t_data),
    .stopstate        (t_stop)
  );

  // ------------------------------------------------------------------ pads
  // One source drives two copies of the pads, both through continuous assignments, so both carry strong
  // strength whatever drives the source (AMD's OBUFDS_DPHY drives strong in LP and supply in HS; the pads of
  // the generator are variables). xp_* go to AMD's receiver, which passes them on to its buffers through its
  // own continuous assignments. clk_p/clk_n/d_p/d_n, the names of tb_exp1.sv, go to the buffers of
  // ftel_dphy_rx and to afe_model.
  bit            src_gen = 1'b0;
  wire           xp_clk_p = src_gen ? g_clk_p : t_clk_p;
  wire           xp_clk_n = src_gen ? g_clk_n : t_clk_n;
  wire [NL-1:0]  xp_d_p   = src_gen ? g_d_p   : t_d_p;
  wire [NL-1:0]  xp_d_n   = src_gen ? g_d_n   : t_d_n;
  wire           clk_p    = src_gen ? g_clk_p : t_clk_p;
  wire           clk_n    = src_gen ? g_clk_n : t_clk_n;
  // +NEG_FRONT=1, the negative test of the front-end check: during HS (as pad_truth sees it) the copy of
  // ftel_dphy_rx carries pull strength, so its buffers give LP-00 while AMD's still follow the HS levels.
  bit            neg_front = 1'b0;
  logic [NL-1:0] p_in_hs;
  logic          p_cl_in_hs;
  wire  [NL-1:0] d_p, d_n;
  for (genvar l = 0; l < NL; l++) begin : g_pad
    assign (strong1, strong0) d_p[l] = (neg_front && p_in_hs[l]) ? 1'bz : xp_d_p[l];
    assign (pull1, pull0)     d_p[l] = (neg_front && p_in_hs[l]) ? xp_d_p[l] : 1'bz;
    assign (strong1, strong0) d_n[l] = (neg_front && p_in_hs[l]) ? 1'bz : xp_d_n[l];
    assign (pull1, pull0)     d_n[l] = (neg_front && p_in_hs[l]) ? xp_d_n[l] : 1'bz;
  end

  // ------------------------------------------------------------------ AMD's receiver
  logic                x_byteclk, x_init_done, x_cl_stop, x_cl_active;
  logic [NL-1:0][7:0]  x_data;
  logic [NL-1:0]       x_valid, x_active, x_sync, x_errsot, x_errsotsync, x_stop;

  // One name for the three branches, so the front-end check below reaches AMD's buffers at any lane count.
  if (NL == 4) begin : g_x
    xrx u_xrx (
      .core_clk (core_clk), .core_rst (xrst), .rxbyteclkhs (x_byteclk), .clkoutphy_out (), .pll_lock_out (),
      .system_rst_out (), .init_done (x_init_done), .cl_stopstate (x_cl_stop), .cl_enable (1'b1),
      .cl_ulpsactivenot (), .cl_rxclkactivehs (x_cl_active), .cl_rxulpsclknot (),
      .dl0_stopstate (x_stop[0]), .dl0_enable (1'b1), .dl0_ulpsactivenot (), .dl0_rxdatahs (x_data[0]),
      .dl0_rxvalidhs (x_valid[0]), .dl0_rxactivehs (x_active[0]), .dl0_rxsynchs (x_sync[0]),
      .dl0_forcerxmode (1'b0), .dl0_rxclkesc (), .dl0_rxlpdtesc (), .dl0_rxulpsesc (), .dl0_rxtriggeresc (),
      .dl0_rxdataesc (), .dl0_rxvalidesc (), .dl0_errsoths (x_errsot[0]), .dl0_errsotsynchs (x_errsotsync[0]),
      .dl0_erresc (), .dl0_errsyncesc (), .dl0_errcontrol (),
      .dl1_stopstate (x_stop[1]), .dl1_enable (1'b1), .dl1_ulpsactivenot (), .dl1_rxdatahs (x_data[1]),
      .dl1_rxvalidhs (x_valid[1]), .dl1_rxactivehs (x_active[1]), .dl1_rxsynchs (x_sync[1]),
      .dl1_forcerxmode (1'b0), .dl1_rxclkesc (), .dl1_rxlpdtesc (), .dl1_rxulpsesc (), .dl1_rxtriggeresc (),
      .dl1_rxdataesc (), .dl1_rxvalidesc (), .dl1_errsoths (x_errsot[1]), .dl1_errsotsynchs (x_errsotsync[1]),
      .dl1_erresc (), .dl1_errsyncesc (), .dl1_errcontrol (),
      .dl2_stopstate (x_stop[2]), .dl2_enable (1'b1), .dl2_ulpsactivenot (), .dl2_rxdatahs (x_data[2]),
      .dl2_rxvalidhs (x_valid[2]), .dl2_rxactivehs (x_active[2]), .dl2_rxsynchs (x_sync[2]),
      .dl2_forcerxmode (1'b0), .dl2_rxclkesc (), .dl2_rxlpdtesc (), .dl2_rxulpsesc (), .dl2_rxtriggeresc (),
      .dl2_rxdataesc (), .dl2_rxvalidesc (), .dl2_errsoths (x_errsot[2]), .dl2_errsotsynchs (x_errsotsync[2]),
      .dl2_erresc (), .dl2_errsyncesc (), .dl2_errcontrol (),
      .dl3_stopstate (x_stop[3]), .dl3_enable (1'b1), .dl3_ulpsactivenot (), .dl3_rxdatahs (x_data[3]),
      .dl3_rxvalidhs (x_valid[3]), .dl3_rxactivehs (x_active[3]), .dl3_rxsynchs (x_sync[3]),
      .dl3_forcerxmode (1'b0), .dl3_rxclkesc (), .dl3_rxlpdtesc (), .dl3_rxulpsesc (), .dl3_rxtriggeresc (),
      .dl3_rxdataesc (), .dl3_rxvalidesc (), .dl3_errsoths (x_errsot[3]), .dl3_errsotsynchs (x_errsotsync[3]),
      .dl3_erresc (), .dl3_errsyncesc (), .dl3_errcontrol (),
      .clk_rxp (xp_clk_p), .clk_rxn (xp_clk_n), .data_rxp (xp_d_p), .data_rxn (xp_d_n)
    );
  end else if (NL == 2) begin : g_x
    xrx u_xrx (
      .core_clk (core_clk), .core_rst (xrst), .rxbyteclkhs (x_byteclk), .clkoutphy_out (), .pll_lock_out (),
      .system_rst_out (), .init_done (x_init_done), .cl_stopstate (x_cl_stop), .cl_enable (1'b1),
      .cl_ulpsactivenot (), .cl_rxclkactivehs (x_cl_active), .cl_rxulpsclknot (),
      .dl0_stopstate (x_stop[0]), .dl0_enable (1'b1), .dl0_ulpsactivenot (), .dl0_rxdatahs (x_data[0]),
      .dl0_rxvalidhs (x_valid[0]), .dl0_rxactivehs (x_active[0]), .dl0_rxsynchs (x_sync[0]),
      .dl0_forcerxmode (1'b0), .dl0_rxclkesc (), .dl0_rxlpdtesc (), .dl0_rxulpsesc (), .dl0_rxtriggeresc (),
      .dl0_rxdataesc (), .dl0_rxvalidesc (), .dl0_errsoths (x_errsot[0]), .dl0_errsotsynchs (x_errsotsync[0]),
      .dl0_erresc (), .dl0_errsyncesc (), .dl0_errcontrol (),
      .dl1_stopstate (x_stop[1]), .dl1_enable (1'b1), .dl1_ulpsactivenot (), .dl1_rxdatahs (x_data[1]),
      .dl1_rxvalidhs (x_valid[1]), .dl1_rxactivehs (x_active[1]), .dl1_rxsynchs (x_sync[1]),
      .dl1_forcerxmode (1'b0), .dl1_rxclkesc (), .dl1_rxlpdtesc (), .dl1_rxulpsesc (), .dl1_rxtriggeresc (),
      .dl1_rxdataesc (), .dl1_rxvalidesc (), .dl1_errsoths (x_errsot[1]), .dl1_errsotsynchs (x_errsotsync[1]),
      .dl1_erresc (), .dl1_errsyncesc (), .dl1_errcontrol (),
      .clk_rxp (xp_clk_p), .clk_rxn (xp_clk_n), .data_rxp (xp_d_p), .data_rxn (xp_d_n)
    );
  end else begin : g_x
    xrx u_xrx (
      .core_clk (core_clk), .core_rst (xrst), .rxbyteclkhs (x_byteclk), .clkoutphy_out (), .pll_lock_out (),
      .system_rst_out (), .init_done (x_init_done), .cl_stopstate (x_cl_stop), .cl_enable (1'b1),
      .cl_ulpsactivenot (), .cl_rxclkactivehs (x_cl_active), .cl_rxulpsclknot (),
      .dl0_stopstate (x_stop[0]), .dl0_enable (1'b1), .dl0_ulpsactivenot (), .dl0_rxdatahs (x_data[0]),
      .dl0_rxvalidhs (x_valid[0]), .dl0_rxactivehs (x_active[0]), .dl0_rxsynchs (x_sync[0]),
      .dl0_forcerxmode (1'b0), .dl0_rxclkesc (), .dl0_rxlpdtesc (), .dl0_rxulpsesc (), .dl0_rxtriggeresc (),
      .dl0_rxdataesc (), .dl0_rxvalidesc (), .dl0_errsoths (x_errsot[0]), .dl0_errsotsynchs (x_errsotsync[0]),
      .dl0_erresc (), .dl0_errsyncesc (), .dl0_errcontrol (),
      .clk_rxp (xp_clk_p), .clk_rxn (xp_clk_n), .data_rxp (xp_d_p), .data_rxn (xp_d_n)
    );
  end

  // ------------------------------------------------------------------ ftel_dphy_rx behind its front end
  logic [NL-1:0]           a_lp_dp, a_lp_dn, a_hs_bit, a_in_hs, f_hs_en, f_term_en;
  logic                    a_cl_lp_dp, a_cl_lp_dn, a_cl_hs_clk, a_cl_in_hs, f_cl_hs_en, f_cl_term_en;
  logic                    f_byteclk, f_init_done, f_cl_stop, f_cl_active;
  logic [NL-1:0][7:0]      f_data;
  logic [NL-1:0]           f_valid, f_active, f_sync, f_errsot, f_errsotsync, f_stop;
  logic [NL-1:0][SELW-1:0] f_lane_map;
  logic [C_HS_SETTLE_CYC_W-1:0]     cfg_hs_settle  = C_HS_SETTLE_CYC_RST;
  logic [C_CLK_SETTLE_CYC_W-1:0]    cfg_clk_settle = C_CLK_SETTLE_CYC_RST;
  logic [C_TINIT_CYC_W-1:0]         cfg_tinit      = C_TINIT_CYC_RST;
  logic [C_EOT_SKIP_BYTES_W-1:0]    cfg_eot_skip   = C_EOT_SKIP_BYTES_RST;

  initial for (int l = 0; l < NL; l++) f_lane_map[l] = SELW'(l);

  afe_model #(.NL(NL)) u_afe (
    .clk_p      (clk_p),
    .clk_n      (clk_n),
    .d_p        (d_p),
    .d_n        (d_n),
    .hs_en      (f_hs_en),
    .term_en    (f_term_en),
    .cl_hs_en   (f_cl_hs_en),
    .cl_term_en (f_cl_term_en),
    .lp_dp      (a_lp_dp),
    .lp_dn      (a_lp_dn),
    .hs_bit     (a_hs_bit),
    .cl_lp_dp   (a_cl_lp_dp),
    .cl_lp_dn   (a_cl_lp_dn),
    .cl_hs_clk  (a_cl_hs_clk),
    .in_hs      (a_in_hs),
    .cl_in_hs   (a_cl_in_hs)
  );

  // The decoder of the pads reads the source, as AMD's receiver does; its line state is compared with afe_model's.
  pad_truth #(.NL(NL)) u_pt (
    .clk_p        (xp_clk_p),
    .clk_n        (xp_clk_n),
    .d_p          (xp_d_p),
    .d_n          (xp_d_n),
    .afe_in_hs    (a_in_hs),
    .afe_cl_in_hs (a_cl_in_hs),
    .in_hs        (p_in_hs),
    .cl_in_hs     (p_cl_in_hs)
  );

  // +AFE=xil (default): IBUFDS_DPHY, the D-PHY input buffer of AMD's receiver, one per lane, with the
  // SIM_DEVICE of AMD's IP; the LP receivers stay enabled, as in AMD's IP. The pads reach it through the
  // continuous assignments above, with strong strength, as they reach the buffers of AMD's IP through its own:
  // both see the same front end (LP outputs follow the HS levels; the HS output keeps its last value at
  // LP-11). +AFE=model: afe_model. afe_model checks the line state and the enables in both cases.
  // (This block, the front-end check and the wrap below are the code of tb_exp1.sv.)
  logic [NL-1:0] b_lp_dp, b_lp_dn, b_hs_bit, r_lp_dp, r_lp_dn, r_hs_bit;
  logic          b_cl_lp_dp, b_cl_lp_dn, b_cl_hs_clk, r_cl_lp_dp, r_cl_lp_dn, r_cl_hs_clk;
  bit            afe_xil = 1'b1;

  for (genvar l = 0; l < NL; l++) begin : g_ibuf
    IBUFDS_DPHY #(.SIM_DEVICE("VERSAL_PREMIUM")) u_ibuf (
      .HSRX_O       (b_hs_bit[l]),
      .LPRX_O_N     (b_lp_dn[l]),
      .LPRX_O_P     (b_lp_dp[l]),
      .HSRX_DISABLE (~f_hs_en[l]),
      .I            (d_p[l]),
      .IB           (d_n[l]),
      .LPRX_DISABLE (1'b0)
    );
  end

  IBUFDS_DPHY #(.SIM_DEVICE("VERSAL_PREMIUM")) u_cl_ibuf (
    .HSRX_O       (b_cl_hs_clk),
    .LPRX_O_N     (b_cl_lp_dn),
    .LPRX_O_P     (b_cl_lp_dp),
    .HSRX_DISABLE (~f_cl_hs_en),
    .I            (clk_p),
    .IB           (clk_n),
    .LPRX_DISABLE (1'b0)
  );

  assign r_lp_dp     = afe_xil ? b_lp_dp     : a_lp_dp;
  assign r_lp_dn     = afe_xil ? b_lp_dn     : a_lp_dn;
  assign r_hs_bit    = afe_xil ? b_hs_bit    : a_hs_bit;
  assign r_cl_lp_dp  = afe_xil ? b_cl_lp_dp  : a_cl_lp_dp;
  assign r_cl_lp_dn  = afe_xil ? b_cl_lp_dn  : a_cl_lp_dn;
  assign r_cl_hs_clk = afe_xil ? b_cl_hs_clk : a_cl_hs_clk;

  // Same front end, checked: the LP outputs of AMD's buffers (wires of xrx_support in AMD's IP) must equal
  // those of the buffers above at every change, 2 ps after it (both have a 1 ps delay).
  int fe_diffs = 0, fe_events = 0;
`ifndef TN1_STUB
  `define TN1_XS g_x.u_xrx.inst.inst.xrx_rx_support_i
  wire [3:0] x_lp_dp = {`TN1_XS.rx_dl3_lp_dp_w, `TN1_XS.rx_dl2_lp_dp_w, `TN1_XS.rx_dl1_lp_dp_w, `TN1_XS.rx_dl0_lp_dp_w};
  wire [3:0] x_lp_dn = {`TN1_XS.rx_dl3_lp_dn_w, `TN1_XS.rx_dl2_lp_dn_w, `TN1_XS.rx_dl1_lp_dn_w, `TN1_XS.rx_dl0_lp_dn_w};
  wire       x_cl_lp_dp = `TN1_XS.rx_cl_lp_dp_w;
  wire       x_cl_lp_dn = `TN1_XS.rx_cl_lp_dn_w;
  `undef TN1_XS

  always @(x_lp_dp, x_lp_dn, x_cl_lp_dp, x_cl_lp_dn, b_lp_dp, b_lp_dn, b_cl_lp_dp, b_cl_lp_dn) begin : p_fe_chk
    #0.002;
    fe_events++;
    if ({x_cl_lp_dp, x_cl_lp_dn, x_lp_dp[NL-1:0], x_lp_dn[NL-1:0]} !== {b_cl_lp_dp, b_cl_lp_dn, b_lp_dp, b_lp_dn})
      fe_diffs++;
  end
`endif

  // The pads of AMD's TX leave X at 1 ps and both buffers follow at 2 ps. A comparison started by the values at
  // time 0 (as with unused lanes, whose wires stay undriven) lands on that step and can see one side a delta
  // late. The comparisons up to 2.5 ps are therefore printed and not counted.
  initial begin : p_fe_start
    #0.0025;
    $display("TB FRONT END CHECK START: comparisons %0d, differences %0d up to 2.5 ps, not counted (the pads can leave X at 1 ps)",
             fe_events, fe_diffs);
    fe_diffs = 0;
    fe_events = 0;
  end

  m_ftel_dphy_rx_wrap #(.PARA_NUM_LANES(NL)) u_ftel (
    .i_dphy_rx_core_clk              (core_clk),
    .i_dphy_rx_phy_core_rst_n        (f_rst_n),
    .i_dphy_rx_cl_enable             (1'b1),
    .i_dphy_rx_dl_enable             ({NL{1'b1}}),
    .i_dphy_rx_forcerxmode           ({NL{1'b0}}),
    .o_dphy_rx_init_done             (f_init_done),
    .o_dphy_rx_cl_stopstate          (f_cl_stop),
    .o_dphy_rx_stopstate             (f_stop),
    .o_dphy_rx_cl_ulpsactivenot      (),
    .o_dphy_rx_ulpsactivenot         (),
    .o_dphy_rx_rxbyteclkhs           (f_byteclk),
    .o_dphy_rx_cl_rxclkactivehs      (f_cl_active),
    .o_dphy_rx_cl_ulpsclknot         (),
    .o_dphy_rx_rxdatahs              (f_data),
    .o_dphy_rx_rxvalidhs             (f_valid),
    .o_dphy_rx_rxactivehs            (f_active),
    .o_dphy_rx_rxsynchs              (f_sync),
    .o_dphy_rx_rxskewcalhs           (),
    .o_dphy_rx_rxclkesc              (),
    .o_dphy_rx_rxlpdtesc             (),
    .o_dphy_rx_rxulpsesc             (),
    .o_dphy_rx_rxtriggeresc          (),
    .o_dphy_rx_rxdataesc             (),
    .o_dphy_rx_rxvalidesc            (),
    .o_dphy_rx_errsoths              (f_errsot),
    .o_dphy_rx_errsotsynchs          (f_errsotsync),
    .o_dphy_rx_erresc                (),
    .o_dphy_rx_errsyncesc            (),
    .o_dphy_rx_errcontrol            (),
    .o_dphy_rx_sts_cl_state          (),
    .o_dphy_rx_sts_dl_state          (),
    .o_dphy_rx_sts_cl_abort_tgl      (),
    .o_dphy_rx_sts_errsoths_tgl      (),
    .o_dphy_rx_sts_errsotsynchs_tgl  (),
    .o_dphy_rx_sts_erreotsync_tgl    (),
    .o_dphy_rx_sts_hs_rx_timeout_tgl (),
    .o_dphy_rx_sts_erresc_tgl        (),
    .o_dphy_rx_sts_esc_timeout_tgl   (),
    .i_dphy_rx_afe_lp_dp             (r_lp_dp),
    .i_dphy_rx_afe_lp_dn             (r_lp_dn),
    .i_dphy_rx_afe_cl_lp_dp          (r_cl_lp_dp),
    .i_dphy_rx_afe_cl_lp_dn          (r_cl_lp_dn),
    .i_dphy_rx_afe_cl_hs_clk         (r_cl_hs_clk),
    .i_dphy_rx_afe_hs_bit            (r_hs_bit),
    .o_dphy_rx_afe_hs_en             (f_hs_en),
    .o_dphy_rx_afe_term_en           (f_term_en),
    .o_dphy_rx_afe_cl_hs_en          (f_cl_hs_en),
    .o_dphy_rx_afe_cl_term_en        (f_cl_term_en),
    .o_dphy_rx_afe_dly_tap           (),
    .i_dphy_rx_cfg_hs_settle_cyc     (cfg_hs_settle),
    .i_dphy_rx_cfg_clk_settle_cyc    (cfg_clk_settle),
    .i_dphy_rx_cfg_tinit_cyc         (cfg_tinit),
    .i_dphy_rx_cfg_hs_rx_timeout_cyc (C_HS_RX_TIMEOUT_CYC_RST),
    .i_dphy_rx_cfg_esc_timeout_cyc   (C_ESC_TIMEOUT_CYC_RST),
    .i_dphy_rx_cfg_eot_skip_bytes    (cfg_eot_skip),
    .i_dphy_rx_cfg_lane_map          (f_lane_map),
    .i_dphy_rx_cfg_lane_pol          ({NL{1'b0}})
  );

  // ------------------------------------------------------------------ monitors
  ppi_csv_mon #(.NL(NL)) u_mon_x (
    .clk (x_byteclk), .en (mon_en), .data (x_data), .valid (x_valid), .active (x_active), .sync (x_sync),
    .errsot (x_errsot), .errsotsync (x_errsotsync), .stop (x_stop), .cl_stop (x_cl_stop)
  );

  ppi_csv_mon #(.NL(NL)) u_mon_f (
    .clk (f_byteclk), .en (mon_en), .data (f_data), .valid (f_valid), .active (f_active), .sync (f_sync),
    .errsot (f_errsot), .errsotsync (f_errsotsync), .stop (f_stop), .cl_stop (f_cl_stop)
  );

  // With +SRC=gen, the line state the AFE model infers must equal the one the generator drives (as in TN1).
  int afe_state_errors = 0;
  for (genvar l = 0; l < NL; l++) begin : g_state_chk
    always @(hs_truth[l]) begin
      #0.002;
      if (a_in_hs[l] !== hs_truth[l]) afe_state_errors++;
    end
  end
  always @(cl_hs_truth) begin
    #0.002;
    if (a_cl_in_hs !== cl_hs_truth) afe_state_errors++;
  end

  // ------------------------------------------------------------------ payloads (as in tb_exp1.sv)
  logic [8:0] prbs_s [NL];
  int         sync_off = 1;

  initial foreach (prbs_s[l]) prbs_s[l] = 9'h1FF ^ 9'(l * 37);

  function automatic byte unsigned prbs9_byte(int l);
    byte unsigned b;
    for (int i = 0; i < 8; i++) begin
      b[i]      = prbs_s[l][8] ^ prbs_s[l][4];
      prbs_s[l] = {prbs_s[l][7:0], b[i]};
    end
    return b;
  endfunction

  task automatic make_payload(input int id, input int len, input string pattern, input bit uneven,
                              output bq_t bytes [NL]);
    for (int l = 0; l < NL; l++) begin
      int n;
      n = (uneven && l >= NL / 2 && len > 1) ? len - 1 : len;
      bytes[l] = {};
      for (int i = 0; i < n; i++) begin
        byte unsigned b;
        logic [15:0] v;
        case (pattern)
          "prbs9": b = prbs9_byte(l);
          "synclike": begin
            v = 16'(8'hB8) << sync_off;
            case (i % 4)
              0: b = 8'hB8;
              1: b = v[7:0];
              2: b = v[15:8];
              default: begin
                b        = byte'($urandom_range(0, 255));
                sync_off = (sync_off % 7) + 1;
              end
            endcase
          end
          default: b = byte'(i + 64 * l + 16 * id);
        endcase
        bytes[l].push_back(b);
      end
    end
  endtask

  function automatic void parse_list(input string s, ref int q [$]);
    int start = 0, v;
    q = {};
    for (int i = 0; i <= s.len(); i++)
      if (i == s.len() || s[i] == ",") begin
        if (i > start && $sscanf(s.substr(start, i - 1), "%d", v) == 1) q.push_back(v);
        start = i + 1;
      end
  endfunction

  // The bytes given to the line, per lane and burst: E <burst> <lane> <bytes> <payload hex>.
  int expected_fd = 0;

  function automatic void write_expected(input int id, input bq_t bytes [NL]);
    string s;
    for (int l = 0; l < NL; l++) begin
      if (bytes[l].size() == 0) continue;
      s = "";
      for (int i = 0; i < bytes[l].size(); i++) s = {s, $sformatf("%02x", bytes[l][i])};
      $fdisplay(expected_fd, "E %0d %0d %0d %s", id, l, bytes[l].size(), s);
    end
  endfunction

  // ------------------------------------------------------------------ sequence
  string  outdir = ".", lens_s = "1,2,3,4,5,8,16,64,256,1024", pattern = "counter", sel;
  real    rate = 1440.0, ui, v_r, skew;
  int     lens [$], corrupt [$], repeat_n = 1, v_i, v_ok, timeout_us = 2000, id = 0;
  bit     ftel_on = 1'b1, uneven = 1'b0, vcd_on = 1'b0;
  int     truth_fd = 0, truth_gen_fd = 0;
  real    t_xinit = -1.0, t_finit = -1.0, t_tinit = -1.0;

  initial begin : p_watchdog
    #1;
    v_ok = $value$plusargs("TIMEOUT_US=%d", timeout_us);
    #(real'(timeout_us) * 1000.0);
    $display("TB TIMEOUT at %.3f us", $realtime / 1000.0);
    finish_run(1'b1);
  end

  task automatic finish_run(input bit timeout);
    u_mon_x.close();
    u_mon_f.close();
    if (expected_fd != 0) $fclose(expected_fd);
    if (truth_fd != 0) $fclose(truth_fd);
    if (truth_gen_fd != 0) $fclose(truth_gen_fd);
    if (vcd_on) $dumpflush;
    u_afe.report();
    u_pt.report();
    $display("TB FRONT END CHECK: LP outputs of AMD's buffers and of the buffers of ftel_dphy_rx differ at %0d of %0d changes",
             fe_diffs, fe_events);
    if (!src_gen)
      $display("TB TX: init_done %.3f us, clock lane requested %.3f us, running %.3f us (%s), %0d bursts done, %0d lane bursts without HS",
               t_tinit / 1000.0, u_drv.t_cl_request / 1000.0, u_drv.t_cl_running / 1000.0,
               u_drv.cl_active_seen ? string'("cl_txclkactivehs") : string'("cl_stopstate, cl_txclkactivehs never High"),
               u_drv.n_bursts, u_drv.n_no_hs);
    $display("TB DONE %s: NL %0d, rate %.2f Mb/s (UI %.3f ns), %0d bursts, AMD init_done %.3f us, ftel init_done %.3f us, AFE line-state errors %0d",
             timeout ? "TIMEOUT" : "OK", NL, 1000.0 / ui, ui, id, t_xinit / 1000.0, t_finit / 1000.0,
             afe_state_errors);
    $finish;
  endtask

  initial begin : p_main
    bq_t bytes [NL];
    v_ok = $value$plusargs("OUTDIR=%s", outdir);
    v_ok = $value$plusargs("RATE=%f", rate);
    v_ok = $value$plusargs("LENS=%s", lens_s);
    v_ok = $value$plusargs("REPEAT=%d", repeat_n);
    v_ok = $value$plusargs("PATTERN=%s", pattern);
    if ($value$plusargs("UNEVEN=%d", v_i)) uneven = (v_i != 0);
    if ($value$plusargs("FTEL=%d", v_i)) ftel_on = (v_i != 0);
    if ($value$plusargs("AFE_NOISE=%d", v_i)) u_afe.noise = (v_i != 0);
    v_ok = $value$plusargs("CORE_HALF=%f", core_half);
    v_ok = $value$plusargs("TX_CORE_HALF=%f", tx_core_half);
    if ($value$plusargs("AFE=%s", sel)) begin
      if (sel != "xil" && sel != "model") $fatal(1, "TB: +AFE=%s, expected xil or model", sel);
      afe_xil = (sel == "xil");
    end
    if (u_afe.noise && afe_xil) $fatal(1, "TB: +AFE_NOISE=1 needs +AFE=model (the noise is afe_model's)");
    if ($value$plusargs("SRC=%s", sel)) begin
      if (sel != "tx" && sel != "gen") $fatal(1, "TB: +SRC=%s, expected tx or gen", sel);
      src_gen = (sel == "gen");
    end
    if ($value$plusargs("GAP_NS=%f", v_r)) u_drv.gap_ns = v_r;
    if ($value$plusargs("READY0=%d", v_i)) u_drv.ready0 = (v_i != 0);
    if ($value$plusargs("TXLOG=%d", v_i)) u_drv.log_bursts = v_i;
    if ($value$plusargs("VCD=%d", v_i)) vcd_on = (v_i != 0);
    if ($value$plusargs("NEG_FRONT=%d", v_i)) neg_front = (v_i != 0);
    if ($value$plusargs("TX_CORRUPT=%s", sel)) begin
      parse_list(sel, corrupt);
      if (corrupt.size() != 3) $fatal(1, "TB: +TX_CORRUPT=%s, expected <lane>,<burst>,<byte>", sel);
      u_drv.corrupt_lane  = corrupt[0];
      u_drv.corrupt_burst = corrupt[1];
      u_drv.corrupt_byte  = corrupt[2];
    end
    parse_list(lens_s, lens);

    // Half a UI rounded to the 1 ps resolution, so the bit grid of the generator stays exact (as in TN1).
    ui = 2.0 * (real'($rtoi(1000.0 / rate * 500.0 + 0.5)) / 1000.0);
    u_gen.ui = ui;
    u_afe.ui = ui;
    u_pt.ui  = ui;
    // Line timing of the generator (+SRC=gen): inside the D-PHY v1.1 ranges at this rate, as in tb_exp1.sv.
    u_gen.t_lpx         = 75.0;                                         // >= 50
    u_gen.t_hs_prepare  = (40.0 + 4.0 * ui + 85.0 + 6.0 * ui) / 2.0;    // 40 + 4 UI .. 85 + 6 UI
    u_gen.t_hs_zero     = 1.2 * (145.0 + 10.0 * ui) - u_gen.t_hs_prepare;
    u_gen.t_hs_trail    = 1.2 * ((8.0 * ui > 60.0 + 4.0 * ui) ? 8.0 * ui : 60.0 + 4.0 * ui);
    u_gen.t_hs_exit     = 150.0;                                        // >= 100
    u_gen.t_clk_prepare = 66.0;                                         // 38 .. 95
    u_gen.t_clk_zero    = 360.0 - u_gen.t_clk_prepare;                  // PREPARE + ZERO >= 300
    if ($value$plusargs("PREP=%s", sel))
      u_gen.t_hs_prepare = (sel == "min") ? 40.0 + 4.0 * ui : ((sel == "max") ? 85.0 + 6.0 * ui : u_gen.t_hs_prepare);
    if ($value$plusargs("ZERO=%s", sel) && sel == "min") u_gen.t_hs_zero = 145.0 + 10.0 * ui - u_gen.t_hs_prepare;
    if ($value$plusargs("TRAIL=%s", sel)) begin
      if (sel == "min") u_gen.t_hs_trail = (8.0 * ui > 60.0 + 4.0 * ui) ? 8.0 * ui : 60.0 + 4.0 * ui;
      if (sel == "max") u_gen.t_hs_trail = 105.0 + 4.0 * ui;
    end
    if ($value$plusargs("TRAIL_JITTER=%d", v_i)) u_gen.trail_jitter = (v_i != 0) ? 7 : 0;
    if ($value$plusargs("EOT_JUNK=%f", v_r)) u_gen.t_eot_junk = v_r;
    if ($value$plusargs("SEED=%d", v_i)) v_i = $urandom(v_i);
    if ($value$plusargs("EXIT=%s", sel) && sel == "min") u_gen.t_hs_exit = 100.0;
    if ($value$plusargs("LPX=%s", sel) && sel == "min") u_gen.t_lpx = 50.0;
    if ($value$plusargs("TLPX=%f", v_r)) u_gen.t_lpx = v_r;
    if ($value$plusargs("THS_PREPARE=%f", v_r)) u_gen.t_hs_prepare = v_r;
    if ($value$plusargs("THS_ZERO=%f", v_r)) u_gen.t_hs_zero = v_r;
    if ($value$plusargs("THS_TRAIL=%f", v_r)) u_gen.t_hs_trail = v_r;
    if ($value$plusargs("THS_EXIT=%f", v_r)) u_gen.t_hs_exit = v_r;
    if ($value$plusargs("TCLK_PREPARE=%f", v_r)) u_gen.t_clk_prepare = v_r;
    if ($value$plusargs("TCLK_ZERO=%f", v_r)) u_gen.t_clk_zero = v_r;
    for (int l = 0; l < NL; l++)
      if ($value$plusargs($sformatf("SKEW%0d=%%f", l), skew)) u_gen.skew_ps[l] = skew;
    if ($value$plusargs("CLK_SKEW=%f", skew)) u_gen.clk_skew_ps = skew;
    if ($value$plusargs("HS_SETTLE=%d", v_i)) cfg_hs_settle = v_i;
    if ($value$plusargs("CLK_SETTLE=%d", v_i)) cfg_clk_settle = v_i;
    if ($value$plusargs("EOT_SKIP=%d", v_i)) cfg_eot_skip = v_i;
    if ($value$plusargs("TINIT=%d", v_i)) cfg_tinit = v_i;

    expected_fd   = $fopen({outdir, "/expected.txt"}, "w");
    truth_fd      = $fopen({outdir, "/truth.txt"}, "w");
    u_pt.truth_fd = truth_fd;
    if (src_gen) begin
      truth_gen_fd   = $fopen({outdir, "/truth_gen.txt"}, "w");
      u_gen.truth_fd = truth_gen_fd;
    end
    u_mon_x.open({outdir, "/xil_ppi.csv"});
    if (ftel_on) u_mon_f.open({outdir, "/ftel_ppi.csv"});
    if (vcd_on) begin
      $dumpfile({outdir, "/tn2a.vcd"});
      $dumpvars(1, tb_exp2a);
    end
    // string'(): ?: on two text literals pads the shorter one with spaces
    $display("TB START: NL %0d, rate %.2f Mb/s (UI %.3f ns), lengths %p x %0d, pattern %s%s, ftel %0d, source %s",
             NL, 1000.0 / ui, ui, lens, repeat_n, pattern, uneven ? string'(" uneven") : string'(""), ftel_on,
             src_gen ? "line generator" : "AMD's D-PHY TX");
    if (src_gen)
      $display("TB LINE: TLPX %.3f, THS-PREPARE %.3f, THS-ZERO %.3f (PREPARE + ZERO %.3f, min %.3f), THS-TRAIL %.3f (+0..%0d UI, last %.1f ns junk), THS-EXIT %.3f, TCLK-PREPARE %.3f, TCLK-ZERO %.3f ns; skew %p ps, clock %.0f ps; core_clk period %.3f ns",
               u_gen.t_lpx, u_gen.t_hs_prepare, u_gen.t_hs_zero, u_gen.t_hs_prepare + u_gen.t_hs_zero,
               145.0 + 10.0 * ui, u_gen.t_hs_trail, u_gen.trail_jitter, u_gen.t_eot_junk, u_gen.t_hs_exit,
               u_gen.t_clk_prepare, u_gen.t_clk_zero, u_gen.skew_ps, u_gen.clk_skew_ps, 2.0 * core_half);
    else
      $display("TB TX CFG: core clock period %.5f ns (receivers %.5f ns), gap after stopstate %.1f ns, txreadyhs of %s, corrupt lane %0d burst %0d byte %0d",
               2.0 * tx_core_half, 2.0 * core_half, u_drv.gap_ns,
               u_drv.ready0 ? string'("lane 0 for all lanes") : string'("each lane"), u_drv.corrupt_lane, u_drv.corrupt_burst, u_drv.corrupt_byte);
    $display("TB FRONT END: ftel_dphy_rx behind %s%s",
             afe_xil ? string'("IBUFDS_DPHY (SIM_DEVICE VERSAL_PREMIUM), the input buffer of AMD's receiver") :
                       string'("afe_model"),
             neg_front ? string'("; negative test: pull strength at its buffers during HS") : string'(""));
    $display("TB FTEL CFG: hs_settle_cyc %0d, clk_settle_cyc %0d, eot_skip_bytes %0d, tinit_cyc %0d",
             cfg_hs_settle, cfg_clk_settle, cfg_eot_skip, cfg_tinit);

    #100;
    xrst    = 1'b0;
    trst    = src_gen;       // with +SRC=gen the TX stays in reset
    f_rst_n = ftel_on;
    fork
      begin
        wait (x_init_done === 1'b1);
        t_xinit = $realtime;
      end
      begin
        if (ftel_on) begin
          wait (f_init_done === 1'b1);
          t_finit = $realtime;
        end
      end
      begin
        if (!src_gen) begin
          wait (t_init_done === 1'b1);
          t_tinit = $realtime;
        end
      end
    join
    #1000;
    mon_en = 1'b1;
    if (src_gen) begin
      u_gen.start_clock();
      #2000;
    end else begin
      u_drv.start_clock();
    end
    for (int r = 0; r < repeat_n; r++)
      foreach (lens[i]) begin
        make_payload(id, lens[i], pattern, uneven, bytes);
        write_expected(id, bytes);
        u_pt.expect_burst(id, bytes);
        if (src_gen) u_gen.burst(id, bytes);
        else         u_drv.burst(id, bytes);
        id++;
      end
    // Drain: ftel_dphy_rx delivers a burst PARA_EOT_DELAY_BYTES byte clocks after its end (as in TN1).
    #(1000.0 + real'(C_EOT_DELAY_BYTES + 8) * 8.0 * ui);
    finish_run(1'b0);
  end
